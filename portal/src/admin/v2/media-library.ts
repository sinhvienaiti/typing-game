const MEDIA_KINDS: readonly MediaKind[] = ["image", "model", "music", "sfx", "audio", "data"];

function element<K extends keyof HTMLElementTagNameMap>(tag: K, className?: string, text?: string): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  if (className !== undefined) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function actionButton(label: string, onClick: () => void, className = "st-admin-btn"): HTMLButtonElement {
  const node = element("button", className, label);
  node.type = "button";
  node.addEventListener("click", onClick);
  return node;
}

function kindLabel(kind: MediaKind): string {
  const labels: Record<MediaKind, string> = {
    image: "Images",
    model: "3D Models",
    music: "Music",
    sfx: "SFX",
    audio: "Audio",
    data: "Data / Bundles",
  };
  return labels[kind];
}

function provenanceLabel(version: MediaVersion | null): string {
  if (!version) return "No version";
  if (version.provenance === "admin-upload") return "Admin managed";
  if (version.provenance === "generated-runtime") return "Generated by game pipeline";
  if (version.provenance === "code-owned") return "Managed by game files";
  return "External reference";
}

function formatDate(value: string): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "Unknown";
  return new Intl.DateTimeFormat(undefined, {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
}

function formatBytes(value: number | undefined): string {
  if (!value || value <= 0) return "—";
  if (value < 1024) return `${value} B`;
  if (value < 1024 * 1024) return `${(value / 1024).toFixed(1)} KB`;
  return `${(value / (1024 * 1024)).toFixed(1)} MB`;
}

function currentVersion(detail: MediaAssetDetailPayload): MediaVersion | null {
  const id = detail.asset.currentVersionId;
  return id ? detail.versions.find((version) => version.assetVersionId === id) ?? null : null;
}

function technicalDetails(detail: MediaAssetDetailPayload, version: MediaVersion | null): HTMLElement {
  const root = element("details", "st-admin-v2-media-section");
  const summary = element("summary", undefined, "Technical details");
  const meta = element("dl", "st-admin-v2-media-meta");
  const append = (label: string, value: string): void => {
    meta.append(element("dt", undefined, label), element("dd", undefined, value));
  };
  append("Asset ID", detail.asset.assetId);
  append("Current version ID", detail.asset.currentVersionId ?? "None");
  if (version?.source.owner) append("Owner", version.source.owner);
  if (version?.source.generator) append("Generator", version.source.generator);
  if (version?.source.sourcePath) append("Source", version.source.sourcePath);
  if (version?.source.license) append("License", version.source.license);
  root.append(summary, meta);
  return root;
}

function renderUsage(references: MediaReference[]): HTMLElement {
  const section = element("section", "st-admin-v2-media-section");
  section.append(element("h3", undefined, "Used by"));
  if (references.length === 0) {
    section.append(element("p", "st-admin-v2-media-readonly", "No canonical domain currently references this exact asset version."));
    return section;
  }
  const list = element("div", "st-admin-v2-media-usage");
  for (const reference of references) {
    const row = element("div", "st-admin-v2-media-usage-row");
    const copy = element("div");
    copy.append(
      element("strong", undefined, `${reference.domain} · ${reference.entityType}`),
      element("span", undefined, `${reference.entityId} · ${reference.field}${reference.revisionId ? ` · revision ${reference.revisionId}` : ""}`),
    );
    row.append(copy, createAdminStatusChip("IN USE", "good"));
    list.append(row);
  }
  section.append(list);
  return section;
}

function renderVersions(detail: MediaAssetDetailPayload): HTMLElement {
  const section = element("section", "st-admin-v2-media-section");
  section.append(element("h3", undefined, "Versions"));
  const list = element("div", "st-admin-v2-media-versions");
  for (const version of detail.versions) {
    const row = element("div", "st-admin-v2-media-version-row");
    const copy = element("div");
    copy.append(
      element("strong", undefined, formatDate(version.createdAt)),
      element("span", undefined, `${provenanceLabel(version)} · ${version.components.length} component${version.components.length === 1 ? "" : "s"}`),
    );
    row.append(copy, version.assetVersionId === detail.asset.currentVersionId
      ? createAdminStatusChip("CURRENT", "good")
      : createAdminStatusChip("HISTORY", "info"));
    list.append(row);
  }
  section.append(list);
  return section;
}

function previewPlaceholder(title: string, message: string): HTMLElement {
  const root = element("div", "st-admin-v2-media-preview-placeholder");
  root.append(element("strong", undefined, title), element("span", undefined, message));
  return root;
}

async function renderPreview(
  host: HTMLElement,
  api: MediaAdminApi,
  detail: MediaAssetDetailPayload,
  activeHandles: Set<MediaPreviewHandle>,
): Promise<void> {
  const version = currentVersion(detail);
  if (!version) {
    host.replaceChildren(previewPlaceholder("No preview available", "This asset has no current version."));
    return;
  }

  const image = version.components.find((component) => component.mimeType.startsWith("image/"));
  const audio = version.components.find((component) => component.mimeType.startsWith("audio/"));
  const component = image ?? audio ?? version.components[0];
  if (!component) {
    host.replaceChildren(previewPlaceholder("No preview available", "This version has no media component."));
    return;
  }

  try {
    const handle = await api.previewHandle(version.assetVersionId, component);
    if (!host.isConnected) {
      handle?.revoke();
      return;
    }
    if (!handle) {
      host.replaceChildren(previewPlaceholder("Preview not available here", `${component.role} is a ${component.storageClass} component.`));
      return;
    }
    activeHandles.add(handle);
    if (component.mimeType.startsWith("image/")) {
      const imageNode = element("img");
      imageNode.alt = `${detail.asset.title} preview`;
      imageNode.src = handle.url;
      host.replaceChildren(imageNode);
      return;
    }
    if (component.mimeType.startsWith("audio/")) {
      const audioNode = element("audio");
      audioNode.controls = true;
      audioNode.preload = "metadata";
      audioNode.src = handle.url;
      host.replaceChildren(audioNode);
      return;
    }
    host.replaceChildren(previewPlaceholder("Asset is available", `${component.format ?? component.mimeType} preview is handled by the consuming game screen.`));
  } catch (error) {
    if (!host.isConnected) return;
    host.replaceChildren(previewPlaceholder("Preview unavailable", error instanceof Error ? error.message : "Unable to load this preview."));
  }
}

function tagsFromInput(value: string): string[] {
  return [...new Set(value.split(",").map((tag) => tag.trim().toLowerCase()).filter(Boolean))];
}

export function renderAdminV2MediaLibrary(helpScope: AdminHelpScope): HTMLElement {
  const root = element("section", "st-admin-v2-media");
  const api = new MediaAdminApi();
  const adminApi = new SpaceTypingAdminApi();
  const previewHandles = new Set<MediaPreviewHandle>();
  let assets: MediaAsset[] = [];
  let selectedAssetId: string | null = null;
  let selectedGeneration = 0;
  let canUpload = false;
  let canArchive = false;
  let searchValue = "";
  let kindValue: MediaKind | "all" = "all";
  let includeArchived = false;

  const uploadToggle = actionButton("Upload media", () => {
    uploadPanel.hidden = !uploadPanel.hidden;
    if (!uploadPanel.hidden) titleInput.focus();
  }, "st-admin-btn primary");
  uploadToggle.disabled = true;

  root.append(createAdminPageHeader({
    eyebrow: "Media",
    title: "Media Library",
    subtitle: "Browse game media and Admin uploads without editing source paths. Runtime-owned assets stay read-only; Admin uploads use immutable versions.",
    actions: [uploadToggle],
    helpScope,
    help: {
      title: "How Media Library works",
      content: "Uploading a file only adds it to the Media Library. It does not change a ship, product, world or any live gameplay setting. A consuming editor must explicitly select an exact media version later.",
    },
  }));

  const uploadPanel = element("section", "st-admin-v2-media-upload");
  uploadPanel.hidden = true;
  const uploadHead = element("div", "st-admin-v2-media-upload-head");
  const uploadCopy = element("div");
  uploadCopy.append(element("h2", undefined, "Upload new media"), element("p", undefined, "Creates a new Admin-managed asset with an immutable first version."));
  uploadHead.append(uploadCopy, actionButton("Close", () => { uploadPanel.hidden = true; }));
  uploadPanel.append(uploadHead);

  const form = element("form", "st-admin-v2-media-form");
  const kindLabelNode = element("label");
  kindLabelNode.append(element("strong", undefined, "Type"));
  const kindSelect = element("select", "st-admin-v2-media-select");
  for (const kind of MEDIA_KINDS) {
    const option = element("option", undefined, kindLabel(kind));
    option.value = kind;
    kindSelect.append(option);
  }
  kindLabelNode.append(kindSelect);

  const titleLabel = element("label");
  titleLabel.append(element("strong", undefined, "Display name"));
  const titleInput = element("input", "st-admin-v2-media-input");
  titleInput.required = true;
  titleInput.maxLength = 240;
  titleInput.placeholder = "e.g. Vanguard portrait";
  titleLabel.append(titleInput);

  const tagsLabel = element("label", "wide");
  tagsLabel.append(element("strong", undefined, "Tags"));
  const tagsInput = element("input", "st-admin-v2-media-input");
  tagsInput.placeholder = "ships, portrait, vanguard";
  tagsLabel.append(tagsInput);

  const fileLabel = element("label", "wide");
  fileLabel.append(element("strong", undefined, "File"));
  const fileInput = element("input");
  fileInput.type = "file";
  fileInput.required = true;
  fileLabel.append(fileInput);

  const formActions = element("div", "st-admin-v2-media-form-actions");
  const safeNote = element("span", "st-admin-v2-media-safe-note", "Safe by default: upload creates library media only. It does not publish or change gameplay references.");
  const uploadStatus = element("span", "st-admin-v2-media-error");
  uploadStatus.setAttribute("role", "status");
  const submit = element("button", "st-admin-btn primary", "Upload to library");
  submit.type = "submit";
  formActions.append(safeNote, uploadStatus, submit);
  form.append(kindLabelNode, titleLabel, tagsLabel, fileLabel, formActions);
  uploadPanel.append(form);
  root.append(uploadPanel);

  const search = createAdminSearchInput({
    label: "Search media",
    placeholder: "Search by name or tag…",
    onInput: (value) => {
      searchValue = value.trim().toLowerCase();
      renderList();
    },
  });
  const filterKind = element("select", "st-admin-v2-media-select");
  filterKind.setAttribute("aria-label", "Filter by media type");
  const allKinds = element("option", undefined, "All media types");
  allKinds.value = "all";
  filterKind.append(allKinds);
  for (const kind of MEDIA_KINDS) {
    const option = element("option", undefined, kindLabel(kind));
    option.value = kind;
    filterKind.append(option);
  }
  filterKind.addEventListener("change", () => {
    kindValue = filterKind.value as MediaKind | "all";
    renderList();
  });
  const archivedLabel = element("label", "st-admin-v2-media-check");
  const archivedCheck = element("input");
  archivedCheck.type = "checkbox";
  archivedCheck.addEventListener("change", () => {
    includeArchived = archivedCheck.checked;
    void loadAssets();
  });
  archivedLabel.append(archivedCheck, document.createTextNode("Show archived"));
  root.append(createAdminFilterBar(search, filterKind, archivedLabel));

  const summary = element("div", "st-admin-v2-media-summary");
  root.append(summary);

  const workspace = element("div", "st-admin-v2-media-workspace");
  const listPanel = element("section", "st-admin-v2-media-list");
  const listHead = element("div", "st-admin-v2-media-list-head");
  const listCopy = element("div");
  listCopy.append(element("h2", undefined, "Library"), element("p", undefined, "Select an item to preview versions and see where it is used."));
  listHead.append(listCopy);
  const listBody = element("div");
  listBody.append(createAdminSkeleton(7));
  listPanel.append(listHead, listBody);

  const detailPanel = element("aside", "st-admin-v2-media-detail");
  const detailBody = element("div", "st-admin-v2-media-detail-empty");
  detailBody.append(createAdminEmptyState({
    title: "Select a media item",
    message: "Preview, ownership, version history and usage will appear here.",
  }));
  detailPanel.append(detailBody);
  workspace.append(listPanel, detailPanel);
  root.append(workspace);

  const clearPreviewHandles = (): void => {
    for (const handle of previewHandles) handle.revoke();
    previewHandles.clear();
  };

  const filteredAssets = (): MediaAsset[] => assets.filter((asset) => {
    if (kindValue !== "all" && asset.kind !== kindValue) return false;
    if (!searchValue) return true;
    return [asset.title, ...asset.tags].some((value) => value.toLowerCase().includes(searchValue));
  });

  function renderSummary(): void {
    const visible = filteredAssets();
    summary.replaceChildren(
      createAdminStatusChip(`${visible.length} shown`, "info"),
      createAdminStatusChip(`${assets.filter((asset) => asset.lifecycle === "active").length} active`, "good"),
      createAdminStatusChip(`${assets.filter((asset) => asset.lifecycle === "archived").length} archived`, assets.some((asset) => asset.lifecycle === "archived") ? "warn" : "info"),
    );
  }

  function renderList(): void {
    renderSummary();
    const rows = filteredAssets();
    listBody.replaceChildren(createAdminEntityTable<MediaAsset>({
      rows,
      rowKey: (asset) => asset.assetId,
      emptyTitle: "No media matches these filters",
      emptyMessage: "Try another search/type filter or upload a new Admin-managed asset.",
      columns: [
        {
          key: "asset",
          label: "Media",
          render: (asset) => {
            const copy = element("div", "st-admin-v2-media-cell-copy");
            const open = element("button", "st-admin-v2-media-name-button", asset.title);
            open.type = "button";
            open.addEventListener("click", () => { void selectAsset(asset.assetId); });
            const tags = asset.tags.length ? asset.tags.slice(0, 3).join(" · ") : "No tags";
            copy.append(open, element("small", undefined, tags));
            return copy;
          },
        },
        { key: "kind", label: "Type", render: (asset) => kindLabel(asset.kind) },
        { key: "versions", label: "Versions", align: "center", render: (asset) => String(asset.versionCount ?? 0) },
        { key: "references", label: "Used by", align: "center", render: (asset) => String(asset.referenceCount ?? 0) },
        { key: "updated", label: "Updated", render: (asset) => formatDate(asset.updatedAt) },
        {
          key: "status",
          label: "Status",
          render: (asset) => createAdminStatusChip(asset.lifecycle === "active" ? "ACTIVE" : "ARCHIVED", asset.lifecycle === "active" ? "good" : "warn"),
        },
      ],
    }));
  }

  async function selectAsset(assetId: string): Promise<void> {
    selectedAssetId = assetId;
    const generation = ++selectedGeneration;
    clearPreviewHandles();
    detailBody.className = "st-admin-v2-media-detail-body";
    detailBody.replaceChildren(createAdminSkeleton(6));
    try {
      const detail = await api.getAsset(assetId);
      if (!root.isConnected || generation !== selectedGeneration || selectedAssetId !== assetId) return;
      renderDetail(detail);
    } catch (error) {
      if (!root.isConnected || generation !== selectedGeneration) return;
      detailBody.replaceChildren(createAdminErrorState({
        title: "Media details unavailable",
        message: adminErrorMessage(error, "Unable to load this media item."),
        retry: () => { void selectAsset(assetId); },
      }));
    }
  }

  function renderDetail(detail: MediaAssetDetailPayload): void {
    clearPreviewHandles();
    const version = currentVersion(detail);
    const adminOwned = version?.provenance === "admin-upload";
    const head = element("div", "st-admin-v2-media-detail-head");
    const copy = element("div");
    copy.append(element("h2", undefined, detail.asset.title), element("p", undefined, detail.asset.tags.length ? detail.asset.tags.join(" · ") : "No tags"));
    head.append(copy);

    const chips = element("div", "st-admin-v2-media-detail-chips");
    chips.append(
      createAdminStatusChip(kindLabel(detail.asset.kind), "info"),
      createAdminStatusChip(provenanceLabel(version), adminOwned ? "good" : "info"),
      createAdminStatusChip(detail.asset.lifecycle === "active" ? "ACTIVE" : "ARCHIVED", detail.asset.lifecycle === "active" ? "good" : "warn"),
    );

    const preview = element("div", "st-admin-v2-media-preview");
    preview.append(previewPlaceholder("Loading preview…", "Resolving the current immutable version."));
    void renderPreview(preview, api, detail, previewHandles);

    const metaSection = element("section", "st-admin-v2-media-section");
    metaSection.append(element("h3", undefined, "At a glance"));
    const meta = element("dl", "st-admin-v2-media-meta");
    const appendMeta = (label: string, value: string): void => {
      meta.append(element("dt", undefined, label), element("dd", undefined, value));
    };
    appendMeta("Ownership", provenanceLabel(version));
    appendMeta("Versions", String(detail.versions.length));
    appendMeta("Used by", String(detail.references.length));
    appendMeta("Updated", formatDate(detail.asset.updatedAt));
    if (version?.components[0]) {
      appendMeta("Primary format", version.components[0].format ?? version.components[0].mimeType);
      appendMeta("Primary size", formatBytes(version.components[0].byteSize));
    }
    metaSection.append(meta);

    const actions = element("div", "st-admin-v2-media-detail-actions");
    if (adminOwned) {
      if (canUpload) {
        const replaceInput = element("input");
        replaceInput.type = "file";
        replaceInput.hidden = true;
        replaceInput.addEventListener("change", async () => {
          const file = replaceInput.files?.[0];
          if (!file) return;
          const replaceButton = actions.querySelector<HTMLButtonElement>("[data-media-replace]");
          if (replaceButton) replaceButton.disabled = true;
          try {
            await api.createVersion(detail.asset.assetId, file);
            await loadAssets();
            await selectAsset(detail.asset.assetId);
          } catch (error) {
            detailBody.prepend(createAdminErrorState({ message: adminErrorMessage(error, "Unable to create a new media version.") }));
          } finally {
            replaceInput.value = "";
            if (replaceButton) replaceButton.disabled = false;
          }
        });
        const replace = actionButton("Upload new version", () => replaceInput.click(), "st-admin-btn primary");
        replace.dataset.mediaReplace = "true";
        actions.append(replace, replaceInput);
      }
      if (canArchive) {
        const archiveLabel = detail.asset.lifecycle === "archived" ? "Restore to library" : "Archive";
        actions.append(actionButton(archiveLabel, () => {
          openAdminConfirmDialog({
            eyebrow: "Media Library",
            title: detail.asset.lifecycle === "archived" ? "Restore this media item?" : "Archive this media item?",
            message: detail.asset.lifecycle === "archived"
              ? "The item will become visible in the normal Media Library again. Gameplay references remain unchanged."
              : "Archiving hides the item from the normal Media Library. It does not delete immutable versions and does not change gameplay references.",
            confirmLabel: detail.asset.lifecycle === "archived" ? "Restore" : "Archive",
            tone: detail.asset.lifecycle === "archived" ? "normal" : "danger",
            onConfirm: async () => {
              await api.setArchived(detail.asset.assetId, detail.asset.lifecycle !== "archived");
              await loadAssets();
              await selectAsset(detail.asset.assetId);
            },
          });
        }, detail.asset.lifecycle === "archived" ? "st-admin-btn" : "st-admin-btn danger"));
      }
    }

    const ownershipNote = adminOwned
      ? element("div", "st-admin-v2-media-readonly", "This is an Admin-managed asset. New uploads create immutable versions; old versions stay available for rollback/reference history.")
      : element("div", "st-admin-v2-media-readonly", "Read-only here. This asset is owned by Space Typing runtime/project files or a generator pipeline. Admin can reference its exact version but cannot replace or archive the source-owned asset.");

    detailBody.replaceChildren(head, chips, preview, ownershipNote, metaSection, renderUsage(detail.references), renderVersions(detail), technicalDetails(detail, version));
    if (actions.childElementCount > 0) detailBody.append(actions);
  }

  async function loadAssets(): Promise<void> {
    listBody.replaceChildren(createAdminSkeleton(7));
    try {
      const payload = await api.listAssets({ includeArchived });
      if (!root.isConnected) return;
      assets = payload.assets;
      renderList();
      if (selectedAssetId && !assets.some((asset) => asset.assetId === selectedAssetId)) {
        selectedAssetId = null;
        clearPreviewHandles();
        detailBody.className = "st-admin-v2-media-detail-empty";
        detailBody.replaceChildren(createAdminEmptyState({
          title: "Media item is hidden by the current filters",
          message: "Enable archived items or select another library item.",
        }));
      }
    } catch (error) {
      if (!root.isConnected) return;
      listBody.replaceChildren(createAdminErrorState({
        title: "Media Library unavailable",
        message: adminErrorMessage(error, "Unable to load Media Library."),
        retry: () => { void loadAssets(); },
      }));
    }
  }

  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const file = fileInput.files?.[0];
    if (!file || !titleInput.value.trim()) return;
    submit.disabled = true;
    uploadStatus.textContent = "Uploading…";
    try {
      const created = await api.createAsset(file, {
        kind: kindSelect.value as MediaKind,
        title: titleInput.value.trim(),
        tags: tagsFromInput(tagsInput.value),
      });
      uploadStatus.textContent = "Uploaded. Gameplay is unchanged until a consuming editor explicitly selects this version.";
      form.reset();
      uploadPanel.hidden = true;
      await loadAssets();
      await selectAsset(created.asset.assetId);
    } catch (error) {
      uploadStatus.textContent = adminErrorMessage(error, "Unable to upload this media file.");
    } finally {
      submit.disabled = false;
    }
  });

  requestAnimationFrame(async () => {
    try {
      const actor = await adminApi.getActor();
      if (!root.isConnected) return;
      canUpload = actor.permissions.includes("media.upload");
      canArchive = actor.permissions.includes("media.delete");
      uploadToggle.disabled = !canUpload;
    } catch {
      if (!root.isConnected) return;
      uploadToggle.disabled = true;
    }
    await loadAssets();
  });

  const observer = new MutationObserver(() => {
    if (root.isConnected) return;
    clearPreviewHandles();
    observer.disconnect();
  });
  observer.observe(document.documentElement, { childList: true, subtree: true });

  return root;
}
