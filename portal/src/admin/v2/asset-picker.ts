import "./asset-picker.css";
import {
  MediaAdminApi,
  type MediaAsset,
  type MediaAssetDetailPayload,
  type MediaKind,
  type MediaPreviewHandle,
  type MediaVersion,
} from "./media-api";
import { createAdminEmptyState, createAdminSearchInput, createAdminSkeleton, createAdminStatusChip } from "./admin-components";

export type MediaAssetSelection = {
  asset: MediaAsset;
  version: MediaVersion;
};

export type AdminMediaAssetPickerOptions = {
  title?: string;
  message?: string;
  allowedKinds?: readonly MediaKind[];
  selectedAssetVersionId?: string | null;
  returnFocus?: HTMLElement | null;
  isVersionCompatible?: (asset: MediaAsset, version: MediaVersion) => boolean;
  incompatibleEmptyMessage?: string;
  onSelect: (selection: MediaAssetSelection) => void | Promise<void>;
};

const ALL_KINDS: readonly MediaKind[] = ["image", "model", "music", "sfx", "audio", "data"];

function element<K extends keyof HTMLElementTagNameMap>(tag: K, className?: string, text?: string): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  if (className !== undefined) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function kindLabel(kind: MediaKind): string {
  const labels: Record<MediaKind, string> = {
    image: "Images",
    model: "3D Models",
    music: "Music",
    sfx: "SFX",
    audio: "Audio",
    data: "Data / Bundles",
  };
  return labels[kind];
}

function formatDate(value: string): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "Unknown date";
  return new Intl.DateTimeFormat(undefined, {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
}

function provenanceLabel(version: MediaVersion): string {
  if (version.provenance === "admin-upload") return "Admin managed";
  if (version.provenance === "generated-runtime") return "Generated by game pipeline";
  if (version.provenance === "code-owned") return "Managed by game files";
  return "External reference";
}

function focusableElements(root: HTMLElement): HTMLElement[] {
  return [...root.querySelectorAll<HTMLElement>(
    'a[href],button:not([disabled]),input:not([disabled]),select:not([disabled]),textarea:not([disabled]),[tabindex]:not([tabindex="-1"])',
  )].filter((node) => !node.hidden && node.getAttribute("aria-hidden") !== "true");
}

function previewPlaceholder(title: string, message: string): HTMLElement {
  const root = element("div", "st-admin-v2-picker-empty");
  root.append(element("div", undefined, `${title}\n${message}`));
  return root;
}

export function openAdminMediaAssetPicker(options: AdminMediaAssetPickerOptions): () => void {
  const api = new MediaAdminApi();
  const previousActive = options.returnFocus ?? (document.activeElement instanceof HTMLElement ? document.activeElement : null);
  const allowedKinds = options.allowedKinds?.length ? [...new Set(options.allowedKinds)] : [...ALL_KINDS];
  const backdrop = element("div", "st-admin-v2-picker-backdrop");
  const dialog = element("section", "st-admin-v2-picker");
  const titleId = `st-admin-media-picker-title-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
  dialog.setAttribute("role", "dialog");
  dialog.setAttribute("aria-modal", "true");
  dialog.setAttribute("aria-labelledby", titleId);

  const head = element("div", "st-admin-v2-picker-head");
  const headCopy = element("div");
  const title = element("h2", undefined, options.title ?? "Choose media");
  title.id = titleId;
  headCopy.append(title, element("p", undefined, options.message ?? "Choose an exact immutable media version. The consuming editor will reference that version, not a moving latest file."));
  const closeButton = element("button", "st-admin-btn", "Close");
  closeButton.type = "button";
  head.append(headCopy, closeButton);

  let query = "";
  let kind: MediaKind | "all" = allowedKinds.length === 1 ? allowedKinds[0] : "all";
  const filter = element("div", "st-admin-v2-picker-filter");
  const search = createAdminSearchInput({
    label: "Search Media Library",
    placeholder: "Search by name or tag…",
    onInput: (value) => {
      query = value.trim().toLowerCase();
      renderAssetList();
    },
  });
  const kindSelect = element("select", "st-admin-v2-picker-select");
  kindSelect.setAttribute("aria-label", "Filter media type");
  if (allowedKinds.length > 1) {
    const all = element("option", undefined, "Allowed media types");
    all.value = "all";
    kindSelect.append(all);
  }
  for (const value of allowedKinds) {
    const option = element("option", undefined, kindLabel(value));
    option.value = value;
    kindSelect.append(option);
  }
  kindSelect.value = kind;
  kindSelect.disabled = allowedKinds.length === 1;
  kindSelect.addEventListener("change", () => {
    kind = kindSelect.value as MediaKind | "all";
    renderAssetList();
  });
  filter.append(search, kindSelect);

  const workspace = element("div", "st-admin-v2-picker-workspace");
  const assetList = element("div", "st-admin-v2-picker-assets");
  assetList.append(createAdminSkeleton(8));
  const detail = element("div", "st-admin-v2-picker-detail");
  detail.append(createAdminEmptyState({
    title: "Select a media item",
    message: "Its immutable versions will appear here.",
  }));
  workspace.append(assetList, detail);

  const foot = element("div", "st-admin-v2-picker-foot");
  const selectionCopy = element("div", "st-admin-v2-picker-selection");
  selectionCopy.append(element("strong", undefined, "No version selected"), element("span", undefined, "Choose a media item and one exact version."));
  const footActions = element("div", "st-admin-v2-picker-actions");
  const cancel = element("button", "st-admin-btn", "Cancel");
  cancel.type = "button";
  const use = element("button", "st-admin-btn primary", "Use selected version");
  use.type = "button";
  use.disabled = true;
  footActions.append(cancel, use);
  foot.append(selectionCopy, footActions);

  dialog.append(head, filter, workspace, foot);
  backdrop.append(dialog);
  document.body.append(backdrop);

  const controller = new AbortController();
  const { signal } = controller;
  const previewHandles = new Set<MediaPreviewHandle>();
  const detailCache = new Map<string, MediaAssetDetailPayload>();
  const compatibleAssetIds = new Set<string>();
  let compatibilityReady = options.isVersionCompatible === undefined;
  let assets: MediaAsset[] = [];
  let selectedAsset: MediaAssetDetailPayload | null = null;
  let selectedVersion: MediaVersion | null = null;
  let closed = false;
  let selecting = false;
  let detailGeneration = 0;

  const clearPreviewHandles = (): void => {
    for (const handle of previewHandles) handle.revoke();
    previewHandles.clear();
  };

  const close = (): void => {
    if (closed || selecting) return;
    closed = true;
    controller.abort();
    clearPreviewHandles();
    backdrop.remove();
    if (previousActive?.isConnected) previousActive.focus();
  };

  const versionCompatible = (asset: MediaAsset, version: MediaVersion): boolean =>
    options.isVersionCompatible?.(asset, version) ?? true;

  const compatibleVersions = (payload: MediaAssetDetailPayload): MediaVersion[] =>
    payload.versions.filter((version) => versionCompatible(payload.asset, version));

  const filteredAssets = (): MediaAsset[] => assets.filter((asset) => {
    if (!allowedKinds.includes(asset.kind)) return false;
    if (!compatibilityReady) return false;
    if (options.isVersionCompatible && !compatibleAssetIds.has(asset.assetId)) return false;
    if (kind !== "all" && asset.kind !== kind) return false;
    if (!query) return true;
    return [asset.title, ...asset.tags].some((value) => value.toLowerCase().includes(query));
  });

  function renderAssetList(): void {
    if (!compatibilityReady) {
      assetList.replaceChildren(createAdminSkeleton(8));
      return;
    }
    const rows = filteredAssets();
    assetList.replaceChildren();
    if (rows.length === 0) {
      assetList.append(createAdminEmptyState({
        title: "No matching media",
        message: options.isVersionCompatible
          ? options.incompatibleEmptyMessage ?? "No compatible immutable versions are available for this field."
          : "Try another search or media type. Archived items are intentionally excluded from the picker.",
      }));
      return;
    }
    for (const asset of rows) {
      const button = element("button", `st-admin-v2-picker-asset${selectedAsset?.asset.assetId === asset.assetId ? " active" : ""}`);
      button.type = "button";
      button.append(
        element("strong", undefined, asset.title),
        element("span", undefined, `${kindLabel(asset.kind)} · ${asset.versionCount ?? 0} version${asset.versionCount === 1 ? "" : "s"} · ${asset.referenceCount ?? 0} use${asset.referenceCount === 1 ? "" : "s"}`),
      );
      button.addEventListener("click", () => { void selectAsset(asset.assetId); });
      assetList.append(button);
    }
  }

  function updateSelection(version: MediaVersion | null): void {
    selectedVersion = version;
    use.disabled = version === null || selectedAsset === null;
    selectionCopy.replaceChildren();
    if (!version || !selectedAsset) {
      selectionCopy.append(element("strong", undefined, "No version selected"), element("span", undefined, "Choose an exact immutable version."));
      return;
    }
    selectionCopy.append(
      element("strong", undefined, selectedAsset.asset.title),
      element("span", undefined, `Exact version · ${formatDate(version.createdAt)} · ${provenanceLabel(version)}`),
    );
  }

  async function renderVersionPreview(host: HTMLElement, version: MediaVersion): Promise<void> {
    clearPreviewHandles();
    const component = version.components.find((entry) => entry.mimeType.startsWith("image/"))
      ?? version.components.find((entry) => entry.mimeType.startsWith("audio/"))
      ?? version.components[0];
    if (!component) {
      host.replaceChildren(previewPlaceholder("Preview unavailable", "This version has no components."));
      return;
    }
    try {
      const handle = await api.previewHandle(version.assetVersionId, component);
      if (!host.isConnected) {
        handle?.revoke();
        return;
      }
      if (!handle) {
        host.replaceChildren(previewPlaceholder("Preview handled by game", `${component.role} is ${component.storageClass}.`));
        return;
      }
      previewHandles.add(handle);
      if (component.mimeType.startsWith("image/")) {
        const image = element("img");
        image.alt = selectedAsset ? `${selectedAsset.asset.title} preview` : "Media preview";
        image.src = handle.url;
        host.replaceChildren(image);
      } else if (component.mimeType.startsWith("audio/")) {
        const audio = element("audio");
        audio.controls = true;
        audio.preload = "metadata";
        audio.src = handle.url;
        host.replaceChildren(audio);
      } else {
        host.replaceChildren(previewPlaceholder("Version selected", `${component.format ?? component.mimeType} will be previewed in the consuming game editor.`));
      }
    } catch (error) {
      host.replaceChildren(previewPlaceholder("Preview unavailable", error instanceof Error ? error.message : "Unable to load preview."));
    }
  }

  function renderDetail(payload: MediaAssetDetailPayload, preferredVersionId?: string | null): void {
    selectedAsset = payload;
    renderAssetList();
    detail.replaceChildren();
    const heading = element("div");
    heading.append(element("h3", undefined, payload.asset.title));
    const chips = element("div", "st-admin-v2-media-detail-chips");
    chips.append(createAdminStatusChip(kindLabel(payload.asset.kind), "info"), createAdminStatusChip(`${payload.references.length} use${payload.references.length === 1 ? "" : "s"}`, payload.references.length ? "good" : "info"));
    heading.append(chips);

    const preview = element("div", "st-admin-v2-picker-preview");
    preview.append(previewPlaceholder("Choose a version", "Preview follows the exact version selection below."));

    const versions = element("div", "st-admin-v2-picker-versions");
    const availableVersions = compatibleVersions(payload);
    const preferred = preferredVersionId
      ? availableVersions.find((version) => version.assetVersionId === preferredVersionId) ?? null
      : availableVersions.find((version) => version.assetVersionId === payload.asset.currentVersionId) ?? availableVersions[0] ?? null;
    updateSelection(preferred);

    if (availableVersions.length === 0) {
      versions.append(createAdminEmptyState({
        title: "No compatible versions",
        message: options.incompatibleEmptyMessage ?? "This media item has no version compatible with this field.",
      }));
    }

    for (const version of availableVersions) {
      const row = element("div", `st-admin-v2-picker-version${selectedVersion?.assetVersionId === version.assetVersionId ? " selected" : ""}`);
      const copy = element("div", "st-admin-v2-picker-version-copy");
      copy.append(
        element("strong", undefined, formatDate(version.createdAt)),
        element("span", undefined, `${provenanceLabel(version)}${version.assetVersionId === payload.asset.currentVersionId ? " · Current library version" : " · Historical version"}`),
      );
      const choose = element("button", "st-admin-btn", selectedVersion?.assetVersionId === version.assetVersionId ? "Selected" : "Select");
      choose.type = "button";
      choose.addEventListener("click", () => {
        updateSelection(version);
        renderDetail(payload, version.assetVersionId);
      });
      row.append(copy, choose);
      versions.append(row);
    }

    detail.append(heading, preview, versions);
    if (preferred) void renderVersionPreview(preview, preferred);
  }

  async function assetDetail(assetId: string): Promise<MediaAssetDetailPayload> {
    const cached = detailCache.get(assetId);
    if (cached) return cached;
    const payload = await api.getAsset(assetId);
    detailCache.set(assetId, payload);
    return payload;
  }

  async function selectAsset(assetId: string, preferredVersionId?: string | null): Promise<void> {
    const generation = ++detailGeneration;
    detail.replaceChildren(createAdminSkeleton(6));
    try {
      const payload = await assetDetail(assetId);
      if (closed || generation !== detailGeneration) return;
      if (options.isVersionCompatible && compatibleVersions(payload).length === 0) {
        detail.replaceChildren(previewPlaceholder("Incompatible media", options.incompatibleEmptyMessage ?? "Choose another media item."));
        return;
      }
      renderDetail(payload, preferredVersionId);
    } catch (error) {
      if (closed || generation !== detailGeneration) return;
      detail.replaceChildren(previewPlaceholder("Unable to load media", error instanceof Error ? error.message : "Try another item."));
    }
  }

  closeButton.addEventListener("click", close, { signal });
  cancel.addEventListener("click", close, { signal });
  backdrop.addEventListener("pointerdown", (event) => {
    if (event.target === backdrop) close();
  }, { signal });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      event.preventDefault();
      close();
      return;
    }
    if (event.key !== "Tab") return;
    const focusables = focusableElements(dialog);
    if (focusables.length === 0) return;
    const first = focusables[0];
    const last = focusables[focusables.length - 1];
    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  }, { signal });

  use.addEventListener("click", async () => {
    if (!selectedAsset || !selectedVersion || selecting) return;
    if (!versionCompatible(selectedAsset.asset, selectedVersion)) return;
    selecting = true;
    use.disabled = true;
    const original = use.textContent;
    use.textContent = "Selecting…";
    try {
      await options.onSelect({ asset: selectedAsset.asset, version: selectedVersion });
      selecting = false;
      closed = true;
      controller.abort();
      clearPreviewHandles();
      backdrop.remove();
      if (previousActive?.isConnected) previousActive.focus();
    } catch (error) {
      selecting = false;
      use.disabled = false;
      use.textContent = original;
      selectionCopy.append(element("span", undefined, error instanceof Error ? error.message : "Unable to use this media version."));
    }
  }, { signal });

  requestAnimationFrame(async () => {
    try {
      const payload = await api.listAssets();
      if (closed) return;
      assets = payload.assets;
      if (options.isVersionCompatible) {
        const candidates = assets.filter((asset) => allowedKinds.includes(asset.kind));
        const details = await Promise.allSettled(candidates.map((asset) => assetDetail(asset.assetId)));
        if (closed) return;
        details.forEach((result) => {
          if (result.status !== "fulfilled") return;
          if (compatibleVersions(result.value).length > 0) compatibleAssetIds.add(result.value.asset.assetId);
        });
        compatibilityReady = true;
      }
      renderAssetList();
      if (options.selectedAssetVersionId) {
        try {
          const selected = await api.getVersion(options.selectedAssetVersionId);
          const asset = assets.find((entry) => entry.assetId === selected.version.assetId);
          if (
            !closed
            && asset !== undefined
            && allowedKinds.includes(asset.kind)
            && versionCompatible(asset, selected.version)
          ) {
            await selectAsset(selected.version.assetId, selected.version.assetVersionId);
          }
        } catch {
          // A stale selection must not block choosing a replacement.
        }
      }
    } catch (error) {
      compatibilityReady = true;
      if (!closed) assetList.replaceChildren(previewPlaceholder("Media Library unavailable", error instanceof Error ? error.message : "Unable to load Media Library."));
    }
    if (!closed) search.focus();
  });

  return close;
}