// A synthetic Audio Lab staging folder (catalogue-2) in a temp dir: tiny fake
// bytes stand in for OGG, so no real media is ever part of the repo.
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

export const LICENCE = "Adobe Firefly Generate Sound Effects, generated by the project owner (Adobe model)";

/** Default rows: families interleave (Deep, Bright Clack, Deep, Bright Clack) to test regrouping. */
export const ROWS = [
  { id: "deep", name: "Deep Velvet", family: "Deep", score: 6.3729, keys: 12, spaces: 4 },
  { id: "bright-clack", name: "Bright Clack Velvet", family: "Bright Clack", score: 6.3979, keys: 10, spaces: 3 },
  { id: "deep-amber", name: "Deep Amber", family: "Deep", score: 6.2501, keys: 11, spaces: 3 },
  {
    id: "raindrop-tile", name: "Raindrop Tile", family: "Bright Clack", score: null, ownerPick: true, keys: 10, spaces: 8,
    note: "Owner picked 30/10/2026 (version A, natural processing). Not scored with the 218 metric.",
  },
];

export function fakeBytes(id, file) {
  return Buffer.from(`OggS fake ${id}/${file}\n`);
}

function fileName(set, number) {
  return `${set}-${String(number).padStart(2, "0")}.ogg`;
}

/** The staging set manifest: 218 rows carry metrics.duration_ms, owner picks durationMs (as today). */
function setManifest(row) {
  const files = [];
  for (let n = 1; n <= row.keys; n += 1) files.push({ set: "key", n });
  for (let n = 1; n <= row.spaces; n += 1) files.push({ set: "space", n });
  if (row.ownerPick) {
    return {
      schema: "typing-keys-firefly/2", id: row.id, name: row.name, family: row.family,
      status: "owner picked version A", licence: LICENCE, source: `${row.id}.wav`,
      files: files.map(({ set, n }) => ({ file: fileName(set, n), set, durationMs: 400 + n })),
      preview: "preview.ogg",
    };
  }
  return {
    schema: "typing-keys-firefly/2", id: row.id, name: row.name, family: row.family, score: row.score,
    status: "owner-approved-source", licence: LICENCE,
    files: files.map(({ set, n }) => ({
      file: fileName(set, n), set, sha256: "0".repeat(64), mono: true,
      metrics: { duration_ms: 100.25 + n, lufs_m_max: -36.1 }, gate: { pass: true }, processing: { trim: true }, source: { take: n },
    })),
    preview: "preview.ogg",
    measurements: { lufs_spread_db: 0.36 },
  };
}

/**
 * Builds staging under a fresh temp dir. `edit(catalogue, manifests)` may change
 * the JSON before it is written. Returns { base, staging, out, cleanup }.
 */
export function makeStaging({ rows = ROWS, edit } = {}) {
  const base = mkdtempSync(path.join(tmpdir(), "typing-feel-test-"));
  const staging = path.join(base, "staging");
  const out = path.join(base, "public");
  mkdirSync(staging, { recursive: true });
  const catalogue = {
    schema: "typing-keys-firefly/catalogue-2", status: "owner-approved-source", builder: "keys-firefly/218",
    profiles: rows.map((row, order) => ({
      id: row.id, name: row.name, family: row.family, score: row.score,
      ...(row.ownerPick ? { ownerPick: true, note: row.note } : {}),
      manifest: `${row.id}/keys-manifest.json`, preview: `${row.id}/preview.ogg`, order,
    })),
  };
  const manifests = Object.fromEntries(rows.map((row) => [row.id, setManifest(row)]));
  edit?.(catalogue, manifests);
  writeFileSync(path.join(staging, "keys-manifest.json"), `${JSON.stringify(catalogue, null, 1)}\n`);
  // Older catalogues and builder notes sit beside it and must be ignored.
  writeFileSync(path.join(staging, "keys-manifest.33-sets.bak.json"), JSON.stringify({ ...catalogue, profiles: [...catalogue.profiles, { id: "ghost", name: "Ghost", family: "Deep", manifest: "ghost/keys-manifest.json", preview: "ghost/preview.ogg", order: 99 }] }));
  writeFileSync(path.join(staging, ".firefly-builder.json"), '{ "builder": "keys-firefly/218" }\n');
  for (const row of rows) {
    const folder = path.join(staging, row.id);
    mkdirSync(folder, { recursive: true });
    const manifest = manifests[row.id];
    writeFileSync(path.join(folder, "keys-manifest.json"), `${JSON.stringify(manifest, null, 1)}\n`);
    writeFileSync(path.join(folder, "keys-manifest.old.bak.json"), "{}\n");
    for (const entry of Array.isArray(manifest.files) ? manifest.files : []) {
      if (typeof entry?.file === "string" && /^(key|space)-\d+\.ogg$/.test(entry.file)) writeFileSync(path.join(folder, entry.file), fakeBytes(row.id, entry.file));
    }
    writeFileSync(path.join(folder, "preview.ogg"), fakeBytes(row.id, "preview.ogg"));
  }
  return { base, staging, out, cleanup: () => rmSync(base, { recursive: true, force: true }) };
}
