def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n', encoding='utf-8')


def component(value):
    if not re.fullmatch(r'[a-z0-9][a-z0-9._-]*', value) or value in ('.', '..'):
        raise ValueError(f'Tên không hợp lệ: {value!r}')
    return value


def under(root, path):
    root, path = Path(root).resolve(), Path(path).resolve()
    if path != root and root not in path.parents:
        raise ValueError(f'Đường ghi vượt --out: {path}')
    return path


def catalogue(game, listing=None):
    """Read actual 212/213 rows; lists constrain ids but never replace spec authority."""
    cards = {p.stem: (p, yaml.safe_load(p.read_text(encoding='utf-8')))
             for p in sorted((LAB / 'specs' / game).glob('*.yaml'))}
    rows = {}
    if listing:
        data = json.loads(Path(listing).read_text(encoding='utf-8'))
        if not isinstance(data, dict) or data.get('game') != game or not isinstance(data.get('rows'), list):
            raise ValueError('--list cần object {game, rows: [...]} của phiếu 212/213')
        for row in data['rows']:
            sid = component(row['id'])
            if sid in rows:
                raise ValueError(f'Id lặp trong danh sách: {sid}')
            rows[sid] = row
    return {sid: {'path': cards[sid][0], 'card': cards[sid][1], 'list': rows.get(sid, {})}
            for sid in (rows if listing else cards) if sid in cards}


def gate_file(path, card, stage):
    a = audio.load_checked(path)
    sp = spec.from_mapping(card)
    m, _ = features.analyze(a, sp)
    result, _ = hygiene.gate(a.data, a.sr, m, sp, stage=stage, subtype=a.subtype)
    return result, m


def split_takes(x, sr, *, mode='onset', threshold_db=-35, min_gap_ms=150, pre_ms=5, tail_floor_db=-60):
    """Use 1 ms peak activity plus an energy-rise detector for hidden overlapping attacks.

    Cuts index the original PCM, never an envelope or a resampled copy. A merged gap is
    deliberately retained when min_gap_ms is large. Overlapping attacks remain reviewable.
    """
    x = np.asarray(x)
    if x.ndim == 1:
        x = x[:, None]
    level = np.max(np.abs(x), axis=1) if len(x) else np.zeros(0)
    peak = float(level.max()) if len(level) else 0
    if peak < 1e-3:
        return []
    if mode == 'whole':
        return [{'startSample': 0, 'endSample': len(x), 'onsetSample': int(np.flatnonzero(level >= peak * 10**(threshold_db/20))[0]),
                 'overlap': False, 'overlapOnsets': []}]
    hop = max(1, round(sr / 1000))
    padded = np.pad(level, (0, (-len(level)) % hop)).reshape(-1, hop)
    env = padded.max(axis=1)
    active = np.flatnonzero(env >= peak * 10**(threshold_db / 20))
    starts = [int(active[0])]
    for left, right in zip(active[:-1], active[1:]):
        if (right - left) * hop >= sr * min_gap_ms / 1000:
            starts.append(int(right))
    # Detect an attack arriving while a previous tail still carries energy. Quiet
    # gaps do not create secondary attacks, so --min-gap-ms retains its merge meaning.
    rms = np.sqrt(np.mean(padded**2, axis=1))
    smooth = ndimage.uniform_filter1d(rms, 2, origin=0)
    rises = []
    for i in range(10, len(smooth) - 1):
        prior = float(np.mean(smooth[i-10:i-2]))
        if np.min(env[i-10:i-2]) > peak * 10**(threshold_db/20) and smooth[i] > max(prior * 2.0, rms.max() * .22):
            if not rises or i - rises[-1] > 25:
                rises.append(i)
    onsets = sorted(set(starts + rises))
    refined = []
    for frame in onsets:
        lo = max(0, (frame - 1) * hop)
        hi = min(len(level), (frame + 2) * hop)
        if frame in starts:
            idx = np.flatnonzero(level[lo:hi] >= peak * 10**(threshold_db/20))
            onset = lo + int(idx[0]) if len(idx) else frame * hop
        else:
            onset = frame * hop
        if not refined or onset - refined[-1] > .020 * sr:
            refined.append(onset)
    out = []
    for i, onset in enumerate(refined):
        nxt = refined[i+1] if i+1 < len(refined) else len(x)
        start = max(0, onset - round(sr * pre_ms / 1000))
        local_peak = max(float(level[onset:nxt].max()), 1e-12)
        idx = np.flatnonzero(level[onset:nxt] >= local_peak * 10**(tail_floor_db/20))
        end = min(nxt, onset + int(idx[-1]) + 1 + hop) if len(idx) else nxt
        overlaps = []
        if i:
            previous_peak = max(float(level[refined[i-1]:onset].max()), 1e-12)
            previous_tail = level[max(refined[i-1], onset - round(.010*sr)):onset]
            if len(previous_tail) and np.sqrt(np.mean(previous_tail**2)) > previous_peak * .01:
                overlaps.append(onset)
                out[-1]['overlap'] = True
                out[-1]['overlapOnsets'].append(onset)
        out.append({'startSample': start, 'endSample': end, 'onsetSample': onset,
                    'overlap': bool(overlaps), 'overlapOnsets': overlaps})
    return out


def source_row(take, original, original_sha, sr, *, model, date=None, prompt=None):
    sha = ledger.sha256_file(take['file'])
    row = {'schema': ledger.LICENCE_SCHEMA_ID, 'kind': 'source', 'key': f'sha256:{sha}', 'sha256': sha,
           'file': Path(take['file']).name, 'origin': 'generated', 'licence': LICENCE,
           'licenceUrl': policy.licence_url(LICENCE), 'licenceCopy': COPY,
           'commercial_ok': True, 'attribution_required': False, 'raw_redistribution_allowed': False,
           'ai_input_allowed': True, 'generator': 'Adobe Firefly Generate Sound Effects',
           'model': model, 'author': 'project owner', 'licenceLabel': LICENCE_LABEL,
           'date': date or dt.datetime.fromtimestamp(original.stat().st_mtime).astimezone().date().isoformat(),
           'derivedFrom': {'sha256': original_sha, 'file': original.name,
                           'startMs': take['startSample'] / sr * 1000, 'endMs': take['endSample'] / sr * 1000}}
    if prompt:
        row['prompt'] = prompt
    return row


def score_take(take, x, sr, card):
    peak = max(float(np.abs(x).max()), 1e-12)
    onset = take['onsetSample'] - take['startSample']
    pre = x[:onset]
    tail = x[-max(1, round(.020*sr)):]
    rms_db = lambda y: float(20*np.log10(max(np.sqrt(np.mean(y*y)) / peak, 1e-12))) if y.size else -240.
    pre_db, tail_db = rms_db(pre), rms_db(tail)
    duration = len(x) / sr * 1000
    target = card['duration']['target_ms']
    components = {'duration': max(0., 1 - abs(duration-target)/target),
                  'preSilence': float(np.clip(-pre_db / 60, 0, 1)),
                  'tailBackground': float(np.clip(-tail_db / 60, 0, 1))}
    take.update(components=components, score=sum(SCORE_WEIGHTS[k]*v for k,v in components.items()),
                durationMs=duration, preSilenceDb=pre_db, tailBackgroundDb=tail_db)


def make_recipe(game, sid, card, listrow, selected):
    def src(t):
        return {'file': t['file'], 'ledger': t['ledger'], 'licenceText': str(LICENCE_TEXT)}
    proposal = card['loudness'].get('proposal') or card['loudness']['file']
    exp = listrow.get('export', {})
    path = exp.get('path') if isinstance(exp, dict) else None
    # Current 212 list has no export field: never guess a runtime destination from game code.
    path = path or listrow.get('exportPath')
    if path and (Path(path).is_absolute() or any(p in ('.', '..') for p in path.split('/'))):
        raise ValueError('export.path vượt thư mục runtime')
    loop = card['playback']['mode'] == 'loop'
    result = {'schema': recipe.SCHEMA_ID, 'game': game, 'id': sid,
              'description': 'Âm Firefly của chủ dự án.' + ('' if path else ' Đường xuất tạm; điều phối cần chốt trước khi gắn game.'),
              'group': card['randomisation']['group'], 'channels': 2 if card['playback']['channels'] == 'stereo' else 1,
              'loop': loop, 'layers': [{'id': 'firefly', 'role': 'whole', 'source': src(selected[0]),
                 'vary': {'swap': [src(t) for t in selected[1:]], 'swapMode': 'cycle'}}],
              'variants': {'count': len(selected), 'seed': 217, 'pitchCents': [0, 0], 'gainDb': [0, 0]},
              'chain': {'normalise': {'mode': proposal['metric'], 'target': proposal['target']},
                        'limiter': {'ceilingDbtp': proposal.get('true_peak_max_dbtp', -1)},
                        'maxLengthMs': card['duration']['max_ms']},
              'export': {'path': path or f'firefly/{sid}', 'ogg': True, 'oggQuality': 1.0}}
    if loop:
        result['chain']['loopCrossfadeMs'] = 50
    recipe.validate(result)
    return result


def ingest_id(game, sid, info, inbox, out, args):
    card, listrow = info['card'], info['list']
    base = under(out, out / game / sid)
    mode = args.split
    if mode == 'auto':
        mode = 'whole' if card['playback']['mode'] == 'loop' or card.get('source_class') in ('ambience', 'music') else 'onset'
    config = dict(mode=mode, threshold_db=args.threshold_db, min_gap_ms=args.min_gap_ms,
                  pre_ms=args.pre_ms, tail_floor_db=args.tail_floor_db)
    doc = {'schema': 'audiolab.firefly.takes/1', 'game': game, 'id': sid, 'run': args.run,
           'split': config, 'weights': SCORE_WEIGHTS, 'files': [], 'takes': [], 'errors': [],
           'found': 0, 'passed': 0, 'selected': 0, 'finalGate': 'BLOCK', 'variants': [],
           'expectedVariants': card['variants'], 'belowMin': True}
    folder = inbox / game / sid
    files = sorted(folder.iterdir()) if folder.is_dir() else []
    for original in files:
        if not original.is_file() or original.suffix.lower() != '.wav':
            doc['files'].append({'file': original.name, 'skipped': True, 'reason': 'không phải WAV'})
            continue
        before = ledger.sha256_file(original)
        mtime = original.stat().st_mtime_ns
        fdoc = {'file': original.name, 'sha256Before': before, 'mtimeBeforeNs': mtime}
        doc['files'].append(fdoc)
        try:
            x, sr = sf.read(original, always_2d=True, dtype='float64')
            fmt = sf.info(original)
            if fmt.format not in ('WAV', 'WAVEX', 'RF64') or not np.isfinite(x).all():
                raise ValueError('WAV không hợp lệ')
            segments = split_takes(x, sr, **config)
            if not segments:
                # Still exercise raw L1 on silence, not merely the onset detector.
                fdoc['rawGate'], _ = gate_file(original, card, 'raw')
                fdoc['reason'] = 'im lặng'
            for t in segments:
                num = len(doc['takes']) + 1
                dest = under(out, base / 'takes' / f'{sid}-t{num:02d}.wav')
                dest.parent.mkdir(parents=True, exist_ok=True)
                sf.write(dest, x[t['startSample']:t['endSample']], sr, subtype=fmt.subtype, format=fmt.format,
                         endian=fmt.endian)
                t.update(file=str(dest), original=original.name, selected=False)
                t['rawGate'], _ = gate_file(dest, card, 'raw')
                t['passed'] = not any(k in hygiene.UNFIXABLE for k in t['rawGate']['blocking'])
                score_take(t, x[t['startSample']:t['endSample']], sr, card)
                t['ledger'] = source_row(t, original, before, sr, model=args.model, date=args.date, prompt=listrow.get('prompt'))
                doc['takes'].append(t)
        except (OSError, ValueError, RuntimeError) as e:
            doc['errors'].append(f'{original.name}: {e}')
            fdoc['reason'] = str(e)
        finally:
            fdoc.update(sha256After=ledger.sha256_file(original), mtimeAfterNs=original.stat().st_mtime_ns)
            fdoc['unchanged'] = fdoc['sha256After'] == before and fdoc['mtimeAfterNs'] == mtime
            if not fdoc['unchanged']:
                doc['errors'].append(f'Inbox thay đổi: {original.name}')
    doc['found'] = len(doc['takes'])
    doc['passed'] = sum(t['passed'] for t in doc['takes'])
    selected, waves = [], []
    for t in sorted(doc['takes'], key=lambda t: (-t['score'], t['file'])):
        if not t['passed'] or t['overlap']:
            continue
        x, _ = sf.read(t['file'], always_2d=True)
        mono = x.mean(axis=1)
        correlation = max((corr_max(mono, y) for y in waves), default=0.)
        t['maxSelectedCorrelation'] = correlation
        if correlation > .95:
            t['reason'] = 'tương quan > 0,95'
            continue
        t['selected'] = True
        selected.append(t)
        waves.append(mono)
        if len(selected) >= card['variants']['target']:
            break
    doc['selected'] = len(selected)
    doc['belowMin'] = len(selected) < card['variants']['min']
    if doc['belowMin']:
        doc['notes'] = ['dưới min']
    if selected:
        try:
            rec = make_recipe(game, sid, card, listrow, selected)
            write_json(under(out, base / 'recipe.json'), rec)
            run_dir = under(out, base / args.run)
            # Clear only audio files previously recorded by this adapter.
            previous = run_dir / 'firefly.json'
            if run_dir.exists() and any(run_dir.iterdir()) and not previous.is_file():
                raise ValueError(f'Lần chạy đã có dữ liệu không thuộc Firefly: {run_dir}')
            if previous.is_file():
                old = json.loads(previous.read_text())
                for rel in old.get('ownedAudio', []):
                    under(out, run_dir / rel).unlink(missing_ok=True)
            built = render.render(rec, out=run_dir, run=args.run, spec=info['path'], date=args.date)
            for v in built.report['variants']:
                q, m = gate_file(run_dir / v['master'], card, 'final')
                doc['variants'].append({'variant': v['variant'], 'master': v['master'], 'runtime': v['runtime'],
                                        'gate': q, 'metrics': m})
            doc['idLevel'] = built.report['idLevel']
            if all(v['gate']['verdict'] == 'PASS' for v in doc['variants']) and not doc['errors']:
                doc['finalGate'] = 'PASS'
        except (OSError, ValueError, RuntimeError, LookupError) as e:
            doc['errors'].append(str(e))
    doc['ok'] = doc['finalGate'] == 'PASS' and not doc['belowMin'] and not doc['errors']
    run_dir = under(out, base / args.run)
    doc['ownedAudio'] = [str(p.relative_to(run_dir)) for p in run_dir.rglob('*') if p.suffix in ('.wav', '.ogg')]
    write_json(under(out, run_dir / 'firefly.json'), doc)
    write_json(under(out, base / 'takes.json'), doc)
    return doc
