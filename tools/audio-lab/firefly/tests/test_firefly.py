def test_rank_duplicate_recipe_outputs_repeat_and_inbox(setup):
    inbox, out, path = setup
    hits(path, seeds=(0, 0, 1, 2, 3, 4))
    before = (ledger.sha256_file(path), path.stat().st_mtime_ns)
    assert ingest(inbox, out) == 0
    doc = read_takes(out)
    assert doc['selected'] == 4
    chosen = [t for t in doc['takes'] if t['selected']]
    assert len([t for t in doc['takes'][:2] if t['selected']]) <= 1
    assert all(set(t['components']) == {'duration', 'preSilence', 'tailBackground'} for t in chosen)
    run = out / 'dragon-hold' / SID / 'test'
    rec = recipe.load(run / 'recipe.json')
    assert not ledger.schema_errors('recipe', rec)
    layer = rec['layers'][0]
    assert layer['vary']['swapMode'] == 'cycle' and len(layer['vary']['swap']) == 3
    assert layer['source']['ledger']['licence'] == 'LicenseRef-Adobe-Firefly-owner'
    assert layer['source']['ledger']['licenceLabel'] == ('Adobe Firefly Generate Sound Effects, '
                                                          'generated by the project owner (Adobe model)')
    assert layer['source']['file']
    for name in ('render.json', 'SOURCES.json', 'licences.rows.jsonl', 'manifest.fragment.json', 'recipe.json'):
        assert (run / name).is_file()
    report = json.loads((run / 'render.json').read_text())
    for v in report['variants']:
        y, sr = sf.read(run / v['master'], always_2d=True)
        assert abs(measure.lufs_m_max(y, sr) - report['idLevel']) <= .5
        assert measure.true_peak_db(y, sr) <= -1
        assert len(y) / sr * 1000 <= 720
    assert doc['finalGate'] == 'PASS'
    hashes = {str(p.relative_to(run)): ledger.sha256_file(p) for p in run.rglob('*') if p.suffix in ('.wav', '.ogg')}
    assert ingest(inbox, out) == 0
    assert hashes == {str(p.relative_to(run)): ledger.sha256_file(p) for p in run.rglob('*') if p.suffix in ('.wav', '.ogg')}
    assert before == (ledger.sha256_file(path), path.stat().st_mtime_ns)
    original, sr = sf.read(path, always_2d=True)
    for t in doc['takes']:
        y, tsr = sf.read(t['file'], always_2d=True)
        assert tsr == sr and sf.info(t['file']).subtype == 'PCM_16'
        np.testing.assert_array_equal(y, original[t['startSample']:t['endSample']])


