def test_split_samples_merge_whole(setup):
    _, _, path = setup
    x, sr = sf.read(path, always_2d=True)
    takes = split_takes(x, sr)
    assert len(takes) == 6
    assert all(abs(t['onsetSample'] / sr - (.5 + i * 1.8)) <= .002 for i, t in enumerate(takes))
    assert len(split_takes(x, sr, min_gap_ms=2000)) == 1
    whole = split_takes(x, sr, mode='whole')
    assert len(whole) == 1 and whole[0]['endSample'] == len(x)


