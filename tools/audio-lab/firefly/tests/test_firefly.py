def test_loop_auto_and_final_block(tmp_path):
    inbox, out = tmp_path / 'in', tmp_path / 'out'
    source = inbox / 'dragon-hold/amb.forest/loop.wav'
    source.parent.mkdir(parents=True)
    # Periodic broadband fixture, not a replacement game asset.
    rng = np.random.default_rng(217)
    unit = rng.normal(0, .04, (SR, 2))
    sf.write(source, np.tile(unit, (6, 1)), SR, subtype='PCM_16')
    args = ['ingest', '--game', 'dragon-hold', '--id', 'amb.forest', '--inbox', str(inbox),
            '--out', str(out), '--run', 'loop']
    assert main(args) == 0
    doc = json.loads((out / 'dragon-hold/amb.forest/takes.json').read_text())
    assert doc['split']['mode'] == 'whole' and doc['found'] == doc['selected'] == 1
    assert doc['finalGate'] == 'PASS'
    assert main(['listen', '--game', 'dragon-hold', '--id', 'amb.forest', '--out', str(out)]) == 0
    # A much-too-short source is raw-fixable but final-blocking; retain its master.
    hits(inbox / 'dragon-hold' / SID / 'short.wav', seeds=(0, 1, 2, 3))
    p = inbox / 'dragon-hold' / SID / 'short.wav'
    x, sr = sf.read(p, always_2d=True)
    for t in [0.5 + i*1.8 for i in range(4)]:
        a = round((t+.10)*sr)
        x[a:round((t+.65)*sr)] = 0
    sf.write(p, x, sr, subtype='PCM_16')
    assert ingest(inbox, out) == 1
    short = read_takes(out)
    assert short['finalGate'] == 'BLOCK' and short['variants']
    assert all((out / 'dragon-hold' / SID / 'test' / v['master']).is_file() for v in short['variants'])


