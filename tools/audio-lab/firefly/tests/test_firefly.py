def hits(path, seeds=(0, 1, 2, 3, 4, 5), times=None, flat=False, silent=False):
    times = times or [0.5 + i * 1.8 for i in range(len(seeds))]
    x = np.zeros((12 * SR, 2))
    for seed, t in zip(seeds, times):
        y = impact(seed, ms=600) * np.exp(np.arange(28800) / SR / .15) * .55
        y[-960:] *= np.linspace(1, 0, 960)
        if flat:
            y[40:60] = .8
        a = round(t * SR)
        x[a:a + len(y)] += y[:, None] * [1, .85]
    if silent:
        x[:] = 0
    path.parent.mkdir(parents=True, exist_ok=True)
    sf.write(path, x, SR, subtype='PCM_16')
    return x, times


