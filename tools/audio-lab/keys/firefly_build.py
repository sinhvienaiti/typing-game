def plot_spectra(specs, path, cache):
    (cache/'matplotlib').mkdir(parents=True, exist_ok=True)
    os.environ['MPLCONFIGDIR'] = str(cache/'matplotlib')
    os.environ['XDG_CACHE_HOME'] = str(cache)
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(12, 6))
    # norm_psd sử dụng cùng FFT 4096 nên mọi mảng chung trục Hz.
    for name, p in specs:
        f = np.linspace(0, SR/2, len(p))
        db = 10*np.log10(p+1e-30)
        ax.semilogx(f[1:], db[1:], label=name, linewidth=1.3)
    ax.set(xlim=(60,16000), xlabel='Frequency (Hz)', ylabel='Mean normalized power density (dB/Hz)',
           ylim=(-115,-50), title='Firefly keyboard profiles — mean spectrum of 10 final keys')
    ax.set_ylabel('Mean power density (dBFS/Hz)')
    ax.grid(True, alpha=.25)
    ax.legend(ncol=2)
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)
