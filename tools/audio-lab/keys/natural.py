# ---------------------------------------------------------------- small helpers
def fmt_num(v: float, nd: int = 1) -> str:
    s = f"{v:.{nd}f}"
    return s.rstrip("0").rstrip(".") if "." in s else s


def fmt_past(v: float, up: bool, nd: int = 2) -> str:
    """A value just outside a limit, rounded toward the side that breaks it, so a refusal never reads as if the value
    sat on the limit (3.96 s stays 3.96, never 4; 50 MiB + 1 byte reads 50.01 MB, never 50)."""
    q = 10 ** nd
    x = (math.ceil(v * q - 1e-6) if up else math.floor(v * q + 1e-6)) / q
    return fmt_num(x, nd)


def khz(rate: int) -> str:
    return f"{fmt_num(rate / 1000, 2)} kHz"


def db(x: float) -> float:
    return float(20 * np.log10(max(float(x), 1e-12)))


def r1(v):
    return None if v is None or not np.isfinite(v) else round(float(v), 1)


def r2(v):
    return None if v is None or not np.isfinite(v) else round(float(v), 2)


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


TOOL_FILES = ("natural.py", "onsets.py")


def _git(args: list[str]) -> str | None:
    try:
        out = subprocess.run(["git", "--no-optional-locks", "-C", str(Path(__file__).resolve().parent), *args],
                             capture_output=True, text=True, timeout=5)
        return out.stdout if out.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


def git_sha() -> str | None:
    out = _git(["rev-parse", "--short=12", "HEAD"])
    return (out or "").strip() or None


def tool_provenance() -> dict:
    """What made the set (Media V2 source.generator, §3.6): HEAD, '+dirty' when the keys tool or the critic has
    changes Git has not recorded (HEAD alone would then name a commit without this code), and the sha256 of the two
    recipe modules, which pin the code whatever Git says."""
    here = Path(__file__).resolve().parent
    sha = git_sha()
    status = _git(["status", "--porcelain", "--untracked-files=all", "--", ".", "../critic"]) if sha else None
    dirty = None if status is None else bool(status.strip())
    version = f"{sha}{'+dirty' if dirty else ''}" if sha else "unknown"
    return {"name": "tools/audio-lab keys natural", "gitSha": sha, "dirty": dirty,
            "files": {name: sha256_file(here / name) for name in TOOL_FILES},
            "generator": f"typing-feel natural-v1 (tools/audio-lab keys natural @{version})"}


def slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:32].strip("-")
    return s if s and s[0].isalnum() and s not in RESERVED_IDS else "new-set"


def title(text: str) -> str:
    words = re.sub(r"[^A-Za-z0-9]+", " ", text).split()
    return " ".join(w[:1].upper() + w[1:] for w in words)[:60] or "New Set"


# ---------------------------------------------------------------- upload rules
def _rule(rules: list, rid: str, label: str, ok: bool, value, limit, message: str = "", level: str = "error") -> None:
    rules.append({"id": rid, "label": label, "ok": bool(ok), "level": level, "value": value, "limit": limit,
                  "message": "" if ok else message})


def check_upload(path: str | Path) -> dict:
    """Upload rules of §3.8 on one file. Returns {ok, errors, warnings, notes, rules, source, analysis}.

    analysis = {'stereo': decoded 48 kHz frames, 'hits': onsets rows, 'floorDb'} when the take could be read."""
    path = Path(path)
    rules: list[dict] = []
    notes: list[str] = []
    res = {"ok": False, "errors": [], "warnings": [], "notes": notes, "rules": rules, "source": {"file": path.name},
           "analysis": None}

    def done():
        res["errors"] = [r["message"] for r in rules if not r["ok"] and r["level"] == "error"]
        res["warnings"] = [r["message"] for r in rules if not r["ok"] and r["level"] == "warning"]
        res["ok"] = not res["errors"]
        return res

    if not path.is_file():
        _rule(rules, "file", "File", False, None, "WAV", f"{path.name} does not exist.")
        return done()
    size = path.stat().st_size
    res["source"]["bytes"] = size
    mb = size / (1024 * 1024)
    _rule(rules, "size", "Size", size <= UPLOAD["maxBytes"], round(mb, 2), 50,
          f"The file is {fmt_past(mb, up=True)} MB; the limit is 50 MB.")
    if size > UPLOAD["maxBytes"]:
        return done()                                       # never read a file this large
    try:
        info = sf.info(str(path))
    except Exception:
        info = None
    if info is None or info.format not in UPLOAD["formats"]:
        what = "" if info is None else f" (it is {info.format_info or info.format})"
        _rule(rules, "format", "File type", False, None, "WAV",
              f"This file is not a WAV file{what}. Export the take as WAV (PCM 16-bit, 24-bit or 32-bit float).")
        return done()
    res["source"].update({"sha256": sha256_file(path), "format": info.format, "subtype": info.subtype,
                          "sampleRate": int(info.samplerate), "channels": int(info.channels),
                          "durationS": round(info.frames / info.samplerate, 3) if info.samplerate else None})
    _rule(rules, "format", "File type", True, info.format, "WAV")
    words = UPLOAD["subtypes"].get(info.subtype) or SUBTYPE_WORDS.get(info.subtype) or info.subtype_info or info.subtype
    _rule(rules, "sampleFormat", "Sample format", info.subtype in UPLOAD["subtypes"], info.subtype,
          list(UPLOAD["subtypes"]), f"The WAV holds {words} samples; use PCM 16-bit, 24-bit or 32-bit float.")
    _rule(rules, "sampleRate", "Sample rate", info.samplerate in UPLOAD["sampleRates"], int(info.samplerate),
          list(UPLOAD["sampleRates"]), f"Sample rate {khz(info.samplerate)}; use 44.1 or 48 kHz.")
    _rule(rules, "channels", "Channels", info.channels in UPLOAD["channels"], int(info.channels), [1, 2],
          f"The file has {info.channels} channels; use mono or stereo.")
    seconds = info.frames / info.samplerate if info.samplerate else 0.0
    _rule(rules, "duration", "Length", UPLOAD["minSeconds"] <= seconds <= UPLOAD["maxSeconds"], round(seconds, 2),
          [UPLOAD["minSeconds"], UPLOAD["maxSeconds"]],
          f"The take is {fmt_past(seconds, up=seconds > UPLOAD['maxSeconds'])} s long; it must be 4 to 30 s.")
    if seconds > 2 * UPLOAD["maxSeconds"] or info.channels not in UPLOAD["channels"]:
        return done()                                       # nothing more worth reading

    # Content: decode once (48 kHz stereo, as the recipe works), find the taps. No ffmpeg is a machine problem
    # (onsets.DecodeError, exit 2), not a fault of the take.
    onsets.ffmpeg()
    try:
        native, native_sr = sf.read(str(path), dtype="float64", always_2d=True)
        if info.channels == 1:          # ffmpeg's mono-to-stereo upmix is -3 dB; copy the channel at unity instead
            stereo = np.repeat(onsets.decode(path, channels=1), 2, axis=1)
        else:
            stereo = onsets.decode(path)
    except Exception as exc:                                # noqa: BLE001 - reported, not raised
        _rule(rules, "decode", "Readable", False, None, None, f"The WAV could not be read: {str(exc).rstrip('.')}.")
        return done()
    if not np.any(native):
        _rule(rules, "silent", "Silence", False, None, None, "The take is silent.")
        return done()
    peak = float(np.abs(native).max())
    res["source"]["peakDbfs"] = r2(db(peak))
    found = onsets.detect(stereo)
    hits = found["hits"]
    res["analysis"] = {"stereo": stereo, "hits": hits, "floorDb": found["floorDb"]}
    usable = [h for h in hits if h["peakDb"] > -UPLOAD["usableWithinDb"] and h["gapToNextMs"] >= UPLOAD["usableGapMs"]]
    main = main_taps(hits)
    res["source"].update({"noiseFloorDbfs": found["floorDb"], "tapsFound": len(hits), "tapsUsable": len(usable),
                          "tapsMain": len(main)})
    _rule(rules, "usableTaps", "Usable taps", len(usable) >= UPLOAD["minUsableTaps"], len(usable),
          UPLOAD["minUsableTaps"],
          f"Found {len(usable)} usable tap{'s' if len(usable) != 1 else ''}; need at least 12, each at least 150 ms "
          "before the next.")
    # natural-v1 keeps a tap only when it also fades 40 dB before the next one (build2 'main'): say early when the
    # set would come out under the contract minimum, so Accept would stay locked.
    _rule(rules, "mainTaps", "Taps that fade out", len(main) >= MIN_SET["key"], len(main), MIN_SET["key"],
          f"Only {len(main)} tap{'s' if len(main) != 1 else ''} fade out by 40 dB before the next one; Format needs "
          f"at least {MIN_SET['key']} for a set (record the taps further apart, or in a quieter room).", "warning")
    # Full scale: a warning per tap, never a refusal (the owner's Hail Stone v4 peaks at -0.07 dBFS, §3.8). A tap that
    # is truly clipped (flat tops) is a different warning: natural-v1 keeps every main tap as recorded, so the critic's
    # clip gate fails on the files made from it and Accept stays locked. clipped_files() runs the recipe's cuts and set
    # gain to say exactly which files, so the warning never claims a lock Format would not give (a 44.1 kHz take
    # resampled to 48 kHz, or a clipped tap the recipe leaves out, does not lock it).
    full = UPLOAD["fullScale"]
    clipped = clipped_files(stereo, hits)
    loud_taps = []
    for n, h in enumerate(hits):
        a = int(round(h["onsetMs"] / 1000 * native_sr))
        b = int(round((h["onsetMs"] + h["gapToNextMs"]) / 1000 * native_sr)) if n + 1 < len(hits) else len(native)
        at = fmt_num(h["onsetMs"] / 1000, 1)
        if h["n"] in clipped:
            loud_taps.append(h)
            names = [f.removesuffix(".ogg") for f in clipped[h["n"]]]
            _rule(rules, f"clipped.{h['n']}", "Clipped tap", False, round(h["onsetMs"] / 1000, 2), "no flat tops",
                  f"Tap at {at} s is clipped (flat tops); Format keeps it as recorded, so {' and '.join(names)} "
                  f"{'fails' if len(names) == 1 else 'fail'} the clip gate and Accept stays locked. Record the take "
                  "again a little quieter.", "warning")
        elif np.abs(native[a:b]).max(initial=0.0) > full:
            loud_taps.append(h)
            _rule(rules, f"fullScale.{h['n']}", "Peak near 0 dBFS", False, round(h["onsetMs"] / 1000, 2), full,
                  f"Tap at {at} s reaches full scale; check it in the A/B.", "warning")
    res["source"]["tapsClipped"] = len(clipped)
    first = int(round(hits[0]["onsetMs"] / 1000 * native_sr)) if hits else len(native)
    if np.abs(native[:first]).max(initial=0.0) > full:
        _rule(rules, "fullScale.head", "Peak near 0 dBFS", False, 0.0, full,
              "The sound before the first tap reaches full scale; check the start of the take.", "warning")
    if not loud_taps and np.abs(native[first:]).max(initial=0.0) <= full:
        _rule(rules, "fullScale", "Peak near 0 dBFS", True, res["source"]["peakDbfs"], full, level="warning")
    _rule(rules, "noiseFloor", "Background noise", found["floorDb"] < UPLOAD["noiseFloorDbfs"], found["floorDb"],
          UPLOAD["noiseFloorDbfs"],
          f"Background noise sits at {fmt_num(found['floorDb'], 1)} dBFS; aim for below -50 dBFS (a dry, close take).",
          "warning")
    loud = [h for h in hits if h["peakDb"] > -UPLOAD["usableWithinDb"]]
    rate = len(loud) / seconds if seconds else 0.0
    res["source"]["tapsPerSecond"] = round(rate, 2)
    notes.append(f"About {fmt_num(rate, 1)} taps a second (about 2 a second works best); record dry, close to the "
                 "microphone, with no music.")
    return done()


# ---------------------------------------------------------------- the recipe (build2.py version A, hail.py)
def main_taps(hits: list[dict]) -> list[dict]:
    return [h for h in hits if h["peakDb"] > MAIN_PEAK_DB and h["decay40Ms"] is not None]


def segment(x: np.ndarray, onset_ms: float, gap_ms: float, max_ms: float = MAX_TAP_MS) -> np.ndarray:
    """Hit plus everything that follows it until just before the next hit; only the very ends are faded."""
    a = max(0, round((onset_ms - 1) / 1000 * SR))
    n = round(min(gap_ms - 2, max_ms) / 1000 * SR)
    seg = x[a:a + n].copy()
    k = min(round(FADE_IN_S * SR), len(seg))
    seg[:k] *= np.linspace(0, 1, k)[:, None]
    f = min(round(FADE_OUT_S * SR), len(seg) // 3)
    if f > 0:
        seg[-f:] *= (0.5 + 0.5 * np.cos(np.linspace(0, np.pi, f)))[:, None]
    return seg


def lower(seg: np.ndarray, st: float = SPACE_SEMITONES) -> np.ndarray:
    """Pitch by playback rate (longer and lower), like a sampler."""
    r = 2 ** (st / 12)
    n = round(len(seg) / r)
    t = np.arange(n) * r
    return np.stack([np.interp(t, np.arange(len(seg)), seg[:, c]) for c in range(seg.shape[1])], axis=1)


def head_db(y: np.ndarray) -> float:
    h = y[:round(EVEN_HEAD_S * SR)]
    return 20 * np.log10(max(float(np.sqrt(np.mean(h ** 2))), 1e-9))


def even_out(segs: list[np.ndarray], amount: float = EVEN_AMOUNT, limit: float = EVEN_LIMIT_DB) -> list[np.ndarray]:
    """Shrink loudness differences by `amount`, never more than `limit` dB, so dynamics stay natural."""
    dbs = [head_db(s) for s in segs]
    mid = float(np.median(dbs))
    return [s * 10 ** (float(np.clip(amount * (mid - d), -limit, limit)) / 20) for s, d in zip(segs, dbs)]


def build(x: np.ndarray, hits: list[dict]) -> dict:
    """Keys and spaces at their working level (before the set gain), with the hit each came from."""
    main = main_taps(hits)
    key_hits = main[:MAX_KEYS]
    keys = even_out([segment(x, h["onsetMs"], h["gapToNextMs"]) for h in key_hits]) if key_hits else []
    by_tail = sorted(range(len(main)), key=lambda i: -main[i]["gapToNextMs"])[:SPACE_COUNT]
    space_hits = [main[i] for i in by_tail]
    spaces = even_out([lower(segment(x, h["onsetMs"], h["gapToNextMs"])) for h in space_hits]) if space_hits else []
    spaces = [s * 10 ** (SPACE_GAIN_DB / 20) for s in spaces]
    return {"main": main, "keyHits": key_hits, "spaceHits": space_hits, "keys": keys, "spaces": spaces}


def set_gain(pool: list[np.ndarray]) -> float:
    """The one gain of the whole set: its loudest sample lands on SET_PEAK_DBFS."""
    return 10 ** (SET_PEAK_DBFS / 20) / max(float(np.abs(s).max()) for s in pool) if pool else 1.0


def set_files(b: dict) -> list[tuple[str, str, dict, np.ndarray]]:
    """(file name, 'key' | 'space', source hit, the PCM handed to the encoder) for every file of the set."""
    gain = set_gain(b["keys"] + b["spaces"])
    made = []
    for prefix, items, hit_rows in (("key", b["keys"], b["keyHits"]), ("space", b["spaces"], b["spaceHits"])):
        for n, (y, h) in enumerate(zip(items, hit_rows), 1):
            made.append((f"{prefix}-{n:02d}.ogg", prefix, h, np.clip(y * gain, -1, 1)))
    return made


def clipped_files(x: np.ndarray, hits: list[dict]) -> dict[int, list[str]]:
    """Tap number -> the files of the set made from it that fail the critic's clip gate (measure_file 'clip')."""
    from critic import hygiene as H
    out: dict[int, list[str]] = {}
    for fname, _prefix, h, pcm in set_files(build(x, hits)):
        c = H.clip_scan(pcm, "FLOAT")
        if c["full_runs"] or c["flat_runs"]:
            out.setdefault(h["n"], []).append(fname)
    return out


def render(ks: list[np.ndarray], ss: list[np.ndarray], seconds: float = DEMO_S, wpm: int = DEMO_WPM) -> np.ndarray:
    """70 WPM typing (build2.py): human timing and level changes, no repeat within 8 taps, fixed seeds."""
    out = np.zeros((round(seconds * SR) + SR, 2))
    step = 60 / (wpm * 5)
    t, rk, rs = 0.25, [], []
    r = np.random.default_rng(SEED_RHYTHM)
    np.random.default_rng(SEED_SPARKLE)          # build2's droplet seed: version A draws nothing from it

    def pick(pool, recent):
        fresh = [i for i in range(len(pool)) if i not in recent[-8:]] or list(range(len(pool)))
        i = int(r.choice(fresh))
        recent.append(i)
        return pool[i]

    for w in WORDS * 3:
        for ch in w + " ":
            y = pick(ss, rs) if ch == " " else pick(ks, rk)
            a = round(t * SR)
            if t > seconds - 0.1:
                return out[:round(seconds * SR)]
            out[a:a + len(y)] += y * 10 ** (r.uniform(-1.2, 1.2) / 20)
            t += step * r.uniform(.82, 1.18) * (1.12 if ch == " " else .97)
    return out[:round(seconds * SR)]


def master(y: np.ndarray, peak_dbfs: float = SET_PEAK_DBFS) -> np.ndarray:
    return y * (10 ** (peak_dbfs / 20) / max(float(np.abs(y).max()), 1e-9))


def fade_tail(y: np.ndarray, seconds: float = PREVIEW_FADE_S) -> np.ndarray:
    y = y.copy()
    f = min(round(seconds * SR), len(y))
    if f > 0:
        y[-f:] *= (0.5 + 0.5 * np.cos(np.linspace(0, np.pi, f)))[:, None]
    return y


# ---------------------------------------------------------------- the raw cut the owner heard (build.py)
def raw_cut(x: np.ndarray, onset: int, gap_ms: float, max_ms: float = 120.0) -> np.ndarray:
    """From 1 ms before the onset to -45 dB below the hit's peak (or 120 ms / the next hit), 10 ms fade out."""
    a = max(0, onset - round(.001 * SR))
    end = min(len(x), onset + round(min(gap_ms - 3, max_ms) / 1000 * SR))
    seg = x[a:end].copy()
    env = np.abs(seg).max(axis=1)
    pk = env.max()
    loud = np.where(env > pk * 10 ** (-45 / 20))[0]
    seg = seg[:max(loud[-1] + round(.004 * SR), round(.015 * SR))]
    seg[:round(.0008 * SR)] *= np.linspace(0, 1, round(.0008 * SR))[:, None]
    f = min(len(seg) // 3, round(.010 * SR))
    seg[-f:] *= np.linspace(1, 0, f)[:, None] ** 2
    return seg


def _rate(seg: np.ndarray, semitones: float) -> np.ndarray:
    ratio = 2 ** (semitones / 12)
    n = round(len(seg) / ratio)
    t = np.arange(n) * ratio
    return np.stack([np.interp(t, np.arange(len(seg)), seg[:, c]) for c in range(seg.shape[1])], axis=1)


def _level(y: np.ndarray, target_db: float = -18.0) -> np.ndarray:
    head = y[:round(.025 * SR)]
    r = float(np.sqrt(np.mean(head ** 2))) or 1e-9
    return y * (10 ** (target_db / 20) / r)


def raw_cut_take(x: np.ndarray, main: list[dict], seconds: float = DEMO_S, wpm: int = DEMO_WPM) -> np.ndarray:
    """build.py's 'raindrop-70wpm-raw-cut': 120 ms cuts levelled, its three playback rates per tap, spaces from the
    8 fullest taps (low + mid), set peak -3 dBFS, same 70 WPM rhythm (seed 7), no other processing."""
    raw_hits = [raw_cut(x, round(h["onsetMs"] / 1000 * SR), h["gapToNextMs"]) for h in main]
    raw_keys = []
    for seg in raw_hits:
        for st in (0.0, -0.7, 0.6):
            raw_keys.append(_level(_rate(seg, st) if st else seg))
    full = sorted(range(len(main)), key=lambda i: -(main[i]["bands"]["low"] + main[i]["bands"]["mid"]))[:SPACE_COUNT]
    raw_spaces = [_level(raw_hits[i], -16.5) for i in full]
    allr = raw_keys + raw_spaces
    g = 10 ** (-3 / 20) / max(float(np.abs(s).max()) for s in allr)
    allr = [s * g for s in allr]
    ks, ss = allr[:len(raw_keys)], allr[len(raw_keys):]
    out = np.zeros((round(seconds * SR), 2))
    step = 60 / (wpm * 5)
    t, rk, rs = 0.25, [], []
    r = np.random.default_rng(SEED_RHYTHM)

    def pick(pool, recent):
        fresh = [i for i in range(len(pool)) if i not in recent[-8:]] or list(range(len(pool)))
        i = int(r.choice(fresh))
        recent.append(i)
        return pool[i]

    for w in WORDS * 3:
        for ch in w + " ":
            y = pick(ss, rs) if ch == " " else pick(ks, rk)
            a = round(t * SR)
            if a + len(y) >= len(out):
                return out
            out[a:a + len(y)] += y * 10 ** (r.uniform(-1.2, 1.2) / 20)
            t += step * r.uniform(.82, 1.18) * (1.12 if ch == " " else .97)
    return out


# ---------------------------------------------------------------- writing
def write_ogg(path: Path, y: np.ndarray) -> np.ndarray:
    """Write OGG Vorbis the way the prototypes did; returns the PCM handed to the encoder."""
    y = np.clip(y, -1, 1)
    sf.write(str(path), y, SR, format="OGG", subtype="VORBIS")
    return y


def write_mp3(path: Path, y: np.ndarray, kbps: int) -> None:
    proc = subprocess.run([onsets.ffmpeg(), "-v", "error", "-nostdin", "-y", "-f", "f64le", "-ar", str(SR), "-ac", "2",
                           "-i", "pipe:0", "-c:a", "libmp3lame", "-b:a", f"{kbps}k", str(path)],
                          input=np.ascontiguousarray(y).astype("<f8").tobytes(), capture_output=True)
    if proc.returncode != 0:
        raise RuntimeError(f"ffmpeg could not write {path.name}: {proc.stderr.decode('utf-8', 'replace').strip()}")


def manifest_text(man: dict) -> str:
    """set-1 text, one file per line (the layout of typing-feel/tools/import-staging.mjs)."""
    head = [f"  {json.dumps(k)}: {json.dumps(man[k], ensure_ascii=False)}," for k in ("schema", "id", "name", "licence", "recipe")]
    files = [f"    {json.dumps({'file': e['file'], 'set': e['set'], 'durationMs': e['durationMs']}, separators=(',', ':'))}"
             for e in man["files"]]
    return "{\n" + "\n".join(head) + "\n  \"files\": [\n" + ",\n".join(files) + "\n  ],\n  \"preview\": " \
        + json.dumps(man["preview"]) + "\n}\n"


def read_pcm(path: Path) -> np.ndarray:
    data, _ = sf.read(str(path), dtype="float64", always_2d=True)
    return data


def pcm_sha256(data: np.ndarray) -> str:
    return hashlib.sha256(np.ascontiguousarray(data, dtype="<f4").tobytes()).hexdigest()


# ---------------------------------------------------------------- measurements of what ships
def strike(mono: np.ndarray, sr: int = SR) -> dict:
    """Where a tap starts and where its main strike lands (1 ms RMS frames, 0.5 ms hop)."""
    from critic import audio as A
    t, rms = A.frame_rms(mono, sr, 1.0, 0.5)
    if not len(rms) or rms.max() <= 0:
        return {"startMs": None, "mainMs": None, "leadInMs": None, "tickDb": None}
    top = float(rms.max())
    i0 = int(np.argmax(rms >= top * 10 ** (LEAD_IN_START_DB / 20)))
    m = int(np.argmax(rms >= top * 10 ** (LEAD_IN_MAIN_DB / 20)))
    p = m
    while p + 1 < len(rms) and rms[p + 1] >= rms[p]:
        p += 1
    lead = float(t[p] - t[i0]) * 1000
    tick = db(float(rms[i0:m].max()) / top) if lead > LEAD_IN_MS and m > i0 else None   # the opening, re the loudest
    return {"startMs": round(float(t[i0]) * 1000, 1), "mainMs": round(float(t[p]) * 1000, 1), "leadInMs": round(lead, 1),
            "tickDb": r1(tick)}


GATES = ("clip", "silent", "tail", "dcOffset", "truePeak", "sampleRate", "channels")


def measure_file(data: np.ndarray, pcm_in: np.ndarray | None = None, sr: int = SR) -> dict:
    """Numbers of one decoded file and the critic L1 hard gates (AUDIO_PIPELINE §4.3.1) that natural-v1 keeps.

    `data` is the decoded OGG (what the games play): numbers, true peak. `pcm_in` is the PCM handed to the encoder
    (the critic's "after the fix chain" stage): clip, tail, DC, silence. Not gates here, reported only: rise time and
    lead-ins (owner kept Hail Stone's, 31/10), LUFS-M (§8.1), mono (natural sets stay stereo), stereo correlation
    (Hail Stone key-21 is -0.14 and the owner kept it), and no long-tail penalty (§8.3)."""
    from critic import audio as A
    from critic import features as F
    from critic import hygiene as H
    from critic.thresholds import L1
    pcm_in = data if pcm_in is None else pcm_in
    mono = data.mean(axis=1)
    peak = float(np.abs(data).max()) if data.size else 0.0
    tp = A.true_peak_dbtp(data) if data.size else float("-inf")
    _, lm = A.sliding_loudness(data, sr, 0.4, 0.01)
    env = F.envelope(mono, sr)
    dyn = F.dynamics(mono, sr, env)
    st = strike(mono, sr)
    start = (st["startMs"] or 0.0) / 1000
    e = mono ** 2
    tot = float(e.sum()) or 1e-30
    after = float(e[int(round((start + ENERGY_AFTER_S) * sr)):].sum())
    mmono = pcm_in.mean(axis=1)
    end = F.ending(mmono, sr, F.envelope(mmono, sr))
    clip = H.clip_scan(pcm_in, "FLOAT")
    dc = A.dc_estimate(pcm_in, sr)
    corr = None
    if data.shape[1] == 2 and np.std(data[:, 0]) > 0 and np.std(data[:, 1]) > 0:
        corr = float(np.corrcoef(data[:, 0], data[:, 1])[0, 1])
    silent = float(np.abs(pcm_in).max(initial=0.0)) < 10 ** (L1["silent_dbfs"] / 20)
    gates = [
        ("clip", clip["full_runs"] == 0 and clip["flat_runs"] == 0),
        ("silent", not silent),
        ("tail", bool(end["end_decayed"] or end["end_faded"])),
        ("dcOffset", dc < L1["dc_max"]),
        ("truePeak", bool(np.isfinite(tp) and tp <= L1["true_peak_max_dbtp"])),
        ("sampleRate", sr == L1["sample_rate"]),
        ("channels", data.shape[1] in (1, 2)),
    ]
    return {
        "durationMs": round(len(data) / sr * 1000),
        "peakDbfs": r2(db(peak)),
        "truePeakDbtp": r2(tp),
        "lufsMMax": r2(float(lm.max())) if len(lm) else None,
        "riseMs": dyn["attack_ms"],
        "headMs": dyn["onset_ms"],
        "mainStrikeMs": st["leadInMs"],
        "leadIn": bool(st["leadInMs"] is not None and st["leadInMs"] > LEAD_IN_MS),
        "tickDb": st["tickDb"],
        "energyAfter120msPct": round(after / tot * 100, 1),
        "endLevelDb": end["end_level_db_rel"],
        "dcOffset": round(float(dc), 6),
        "stereoCorrelation": None if corr is None else round(corr, 3),
        "phaseWarning": bool(corr is not None and corr <= L1["stereo_corr_min"]),
        "gates": {k: bool(v) for k, v in gates},
    }


def source_tail_share(x: np.ndarray, main: list[dict]) -> float | None:
    """build2.py: share of each kept tap's energy that arrives after 120 ms (what the 120 ms raw cut threw away)."""
    tail = whole = 0.0
    for h in main:
        a = round(h["onsetMs"] / 1000 * SR)
        b = round((h["onsetMs"] + min(h["gapToNextMs"], MAX_TAP_MS)) / 1000 * SR)
        tail += float((x[a + round(ENERGY_AFTER_S * SR):b] ** 2).sum())
        whole += float((x[a:b] ** 2).sum())
    return round(tail / whole * 100, 2) if whole > 0 else None


def integrated_lufs(y: np.ndarray) -> float | None:
    from critic import audio as A
    return r2(A.integrated(y, SR))


# ---------------------------------------------------------------- the job
def prepare_out(out: Path) -> None:
    if out.exists() and (not out.is_dir() or any(out.iterdir())):
        raise UsageError(f"Output folder {out} is not empty; give a new folder.")
    out.mkdir(parents=True, exist_ok=True)


def public_check(check: dict) -> dict:
    return {k: v for k, v in check.items() if k != "analysis"}


def format_take(src: Path, out: Path, set_id: str | None = None, name: str | None = None, family: str | None = None,
                licence: str = DEFAULT_LICENCE, arrays: dict | None = None) -> dict:
    """Run the upload rules, then natural-v1. Writes everything into `out`; returns the report.

    `arrays`, when given, receives the PCM handed to each encoder (file name -> float array), for tests."""
    src, out = Path(src), Path(out)
    set_id = set_id or slug(src.stem)
    if not ID_PATTERN.match(set_id) or set_id in RESERVED_IDS:
        raise UsageError(f"Set id {set_id!r} must match {ID_PATTERN.pattern} and must not be 'off'.")
    name = (name or title(src.stem)).strip()
    if not name:
        raise UsageError("Set name is empty.")
    prepare_out(out)
    started = dt.datetime.now(dt.timezone.utc)
    check = check_upload(src)
    report = {
        "schema": REPORT_SCHEMA, "recipe": RECIPE, "status": "refused",
        "tool": tool_provenance(),
        "createdAt": started.isoformat(timespec="seconds").replace("+00:00", "Z"),
        "set": {"id": set_id, "name": name, "family": family, "licence": licence},
        "params": PARAMS,
        "upload": public_check(check),
        "warnings": list(check["warnings"]),
    }
    if not check["ok"]:
        (out / "report.json").write_text(json.dumps(report, indent=1, ensure_ascii=False) + "\n", "utf-8")
        return report

    x, hits = check["analysis"]["stereo"], check["analysis"]["hits"]
    b = build(x, hits)
    keys, spaces = b["keys"], b["spaces"]
    if len(b["main"]) > MAX_KEYS:
        report["warnings"].append(f"{len(b['main'])} main taps found; kept the first {MAX_KEYS} as keys.")
    files, made = [], []
    pool = keys + spaces
    for fname, prefix, h, pcm in set_files(b):
        write_ogg(out / fname, pcm)
        files.append({"file": fname, "set": prefix, "durationMs": round(len(pcm) / SR * 1000)})
        made.append((fname, prefix, h, pcm))
    preview = fade_tail(master(render(keys, spaces, seconds=PREVIEW_S))) if pool else np.zeros((round(PREVIEW_S * SR), 2))
    preview = write_ogg(out / "preview.ogg", preview)
    man = {"schema": SET_SCHEMA, "id": set_id, "name": name, "licence": licence, "recipe": RECIPE, "files": files,
           "preview": "preview.ogg"}
    (out / "keys-manifest.json").write_text(manifest_text(man), "utf-8")

    (out / "ab").mkdir()
    natural = master(render(keys, spaces)) if pool else np.zeros((round(DEMO_S * SR), 2))
    write_mp3(out / "ab" / "natural.mp3", natural, NATURAL_MP3_KBPS)
    rawc = raw_cut_take(x, b["main"][:MAX_KEYS]) if b["main"] else np.zeros((round(DEMO_S * SR), 2))
    write_mp3(out / "ab" / "raw-cut.mp3", rawc, RAW_MP3_KBPS)
    if arrays is not None:          # tests: the float arrays before any encoder (golden fingerprints)
        arrays.update({fname: pcm for fname, _p, _h, pcm in made})
        arrays.update({"preview.ogg": preview, "natural.mp3": natural, "raw-cut.mp3": rawc})

    # Measure what ships: the decoded OGG files.
    rows, lead_ins = [], []
    for fname, prefix, h, pcm in made:
        data = read_pcm(out / fname)
        m = measure_file(data, pcm)
        row = {"file": fname, "set": prefix, "tap": h["n"], "sourceOnsetMs": h["onsetMs"], "gapToNextMs": h["gapToNextMs"],
               "bytes": (out / fname).stat().st_size, "pcmSha256": pcm_sha256(data), **m}
        rows.append(row)
        if m["leadIn"]:
            lead_ins.append({"file": fname, "set": prefix, "mainStrikeMs": m["mainStrikeMs"], "tickDb": m["tickDb"]})
    pdata = read_pcm(out / "preview.ogg")
    pm = measure_file(pdata, preview)
    prev = {"file": "preview.ogg", "bytes": (out / "preview.ogg").stat().st_size, "pcmSha256": pcm_sha256(pdata),
            "fadeOutMs": PREVIEW_FADE_S * 1000, **{k: pm[k] for k in ("durationMs", "peakDbfs", "truePeakDbtp", "lufsMMax",
                                                                     "endLevelDb", "gates")}}

    def span(kind, key):
        vals = [r[key] for r in rows if r["set"] == kind and r[key] is not None]
        return [min(vals), max(vals)] if vals else None

    lm = [r["lufsMMax"] for r in rows if r["lufsMMax"] is not None]
    counts = {"key": len(keys), "space": len(spaces)}
    accept_ok = all(counts[k] >= MIN_SET[k] for k in MIN_SET)
    failed = sorted({f"{r['file']}:{g}" for r in rows for g, ok in r["gates"].items() if not ok}
                    | {f"preview.ogg:{g}" for g, ok in prev["gates"].items() if not ok})
    warnings = report["warnings"]
    for k in MIN_SET:
        if counts[k] < MIN_SET[k]:
            warnings.append(f"Only {counts[k]} {k}{'s' if counts[k] != 1 else ''}; a set needs at least {MIN_SET[k]}, "
                            "so Accept stays locked.")
    for li in lead_ins:
        warnings.append(f"{li['file']}: soft tick, then the main strike {fmt_num(li['mainStrikeMs'], 0)} ms later "
                        "(kept as recorded; listen in the A/B).")
    for r in rows:
        if r["phaseWarning"]:
            warnings.append(f"{r['file']}: left and right partly cancel (stereo correlation {r['stereoCorrelation']}); "
                            "it may sound thin on a mono speaker.")
    for f in failed:
        warnings.append(f"Hard gate failed: {f}.")
    report.update({
        "status": "formatted",
        "taps": {"found": len(hits), "usable": check["source"]["tapsUsable"], "main": len(b["main"]),
                 "keys": counts["key"], "spaces": counts["space"],
                 "rows": [{**h, "role": [r for r, hs in (("key", b["keyHits"]), ("space", b["spaceHits"])) if h in hs]}
                          for h in hits]},
        "counts": counts,
        "minimum": MIN_SET,
        "acceptAllowed": accept_ok and not failed,
        "lengthsMs": {"key": span("key", "durationMs"), "space": span("space", "durationMs")},
        "loudness": {"metric": "LUFS-M max (0.4 s window, padded)", "min": min(lm) if lm else None,
                     "max": max(lm) if lm else None, "spreadDb": r2(max(lm) - min(lm)) if lm else None,
                     "truePeakMaxDbtp": max((r["truePeakDbtp"] for r in rows if r["truePeakDbtp"] is not None), default=None),
                     "peakMaxDbfs": max((r["peakDbfs"] for r in rows if r["peakDbfs"] is not None), default=None)},
        "riseMs": {"key": span("key", "riseMs"), "space": span("space", "riseMs")},
        "energyAfter120msPct": {"key": span("key", "energyAfter120msPct"), "space": span("space", "energyAfter120msPct"),
                                "sourceShare": source_tail_share(x, b["main"][:MAX_KEYS])},
        "leadIns": lead_ins,
        "leadInRule": f"main strike more than {fmt_num(LEAD_IN_MS)} ms after the tap starts (start: first 1 ms frame "
                      f"within {fmt_num(-LEAD_IN_START_DB)} dB of the loudest; main: first frame within "
                      f"{fmt_num(-LEAD_IN_MAIN_DB)} dB, up to its local peak); reported, never trimmed",
        "gates": {"pass": not failed, "failed": failed,
                  "checks": list(GATES),
                  "note": "critic L1 (AUDIO_PIPELINE §4.3.1): true peak on the decoded OGG, clip, tail, DC and silence on "
                          "the PCM handed to the encoder; rise time, lead-ins, LUFS-M, mono and stereo correlation are "
                          "reported, not gated; no long-tail penalty (§8.3)"},
        "files": rows,
        "preview": prev,
        "ab": {"rawCut": {"file": "ab/raw-cut.mp3", "seconds": DEMO_S, "wpm": DEMO_WPM, "lufsI": integrated_lufs(rawc),
                          "recipe": "build.py raw cut: 120 ms per tap, levelled, three playback rates per tap, no EQ"},
               "natural": {"file": "ab/natural.mp3", "seconds": DEMO_S, "wpm": DEMO_WPM, "lufsI": integrated_lufs(natural),
                           "recipe": RECIPE}},
        "manifest": {"file": "keys-manifest.json", "sha256": sha256_file(out / "keys-manifest.json")},
        "seconds": round((dt.datetime.now(dt.timezone.utc) - started).total_seconds(), 2),
    })
    (out / "report.json").write_text(json.dumps(report, indent=1, ensure_ascii=False) + "\n", "utf-8")
    return report


# ---------------------------------------------------------------- CLI
def parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="keys natural", description="Format natural-v1: one owner take -> a keyboard set.")
    ap.add_argument("wav", nargs="?", help="the take (WAV)")
    ap.add_argument("--src", help="the take (same as the positional argument)")
    ap.add_argument("--check", action="store_true", help="upload rules only (§3.8); writes nothing")
    ap.add_argument("--json", action="store_true", help="with --check: print the result as JSON")
    ap.add_argument("--out", help="new or empty folder for the set, the A/B takes and report.json")
    ap.add_argument("--id", dest="set_id", help="set id (default: from the file name)")
    ap.add_argument("--name", help="set name (default: from the file name)")
    ap.add_argument("--family", help="family, recorded in report.json")
    ap.add_argument("--licence", default=DEFAULT_LICENCE)
    ap.add_argument("--recipe", default=RECIPE, choices=[RECIPE])
    return ap


def main(argv: list[str] | None = None) -> int:
    ap = parser()
    a = ap.parse_args(sys.argv[1:] if argv is None else argv)
    src = a.src or a.wav
    if not src or (a.src and a.wav and a.src != a.wav):
        ap.print_usage(sys.stderr)
        print("keys natural: give the take once, as <wav> or --src <wav>.", file=sys.stderr)
        return 2
    try:
        if a.check:
            res = check_upload(src)
            if a.json:
                print(json.dumps(public_check(res), indent=1, ensure_ascii=False))
            else:
                for m in res["errors"]:
                    print(f"refused: {m}")
                for m in res["warnings"]:
                    print(f"warning: {m}")
                for m in res["notes"]:
                    print(f"note: {m}")
                s = res["source"]
                if res["ok"]:
                    print(f"ok: {s.get('tapsUsable')} usable taps of {s.get('tapsFound')}, peak {s.get('peakDbfs')} dBFS, "
                          f"noise floor {s.get('noiseFloorDbfs')} dBFS")
            return 0 if res["ok"] else 1
        if not a.out:
            ap.print_usage(sys.stderr)
            print("keys natural: give --out <folder> (or --check).", file=sys.stderr)
            return 2
        rep = format_take(Path(src), Path(a.out), a.set_id, a.name, a.family, a.licence)
    except (UsageError, onsets.DecodeError) as exc:
        print(f"keys natural: {exc}", file=sys.stderr)
        return 2
    except Exception as exc:                                # noqa: BLE001 - one line for the Admin job log
        print(f"keys natural: Format failed: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 3
    if rep["status"] != "formatted":
        for m in rep["upload"]["errors"]:
            print(f"refused: {m}", file=sys.stderr)
        return 1
    print(f"{rep['set']['id']}: {rep['counts']['key']} keys, {rep['counts']['space']} spaces, "
          f"{len(rep['leadIns'])} lead-ins, gates {'pass' if rep['gates']['pass'] else 'FAIL'}, "
          f"accept {'allowed' if rep['acceptAllowed'] else 'locked'} -> {a.out}")
    for w in rep["warnings"]:
        print(f"warning: {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
