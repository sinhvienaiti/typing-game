function serialize(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function describe(value) {
  return JSON.stringify(value) ?? String(value);
}

/** natural.py slug(): the default set id from a file name. */
export function slugFromName(text) {
  const value = String(text ?? "").replace(/\.[A-Za-z0-9]{1,8}$/, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 32).replace(/-+$/, "");
  return value && /^[a-z0-9]/.test(value) && !RESERVED_IDS.has(value) ? value : "new-set";
}

/** natural.py title(): the default set name from a file name. */
export function titleFromName(text) {
  const words = String(text ?? "").replace(/\.[A-Za-z0-9]{1,8}$/, "").split(/[^A-Za-z0-9]+/).filter(Boolean);
  return words.map((word) => word[0].toUpperCase() + word.slice(1)).join(" ").slice(0, SET_NAME_MAX).trim() || "New Set";
}

function cleanText(value, label, max, { required = true } = {}) {
  if (value === undefined || value === null || value === "") {
    if (required) throw new TypingFeelJobError(`${label} is required.`);
    return null;
  }
  if (typeof value !== "string" || value.trim() !== value || value === "" || value.length > max || CONTROL.test(value)) {
    throw new TypingFeelJobError(`${label} must be text of 1 to ${max} characters without leading or trailing spaces.`);
  }
  return value;
}

function cleanSetId(value, label = "Set id") {
  if (typeof value !== "string" || !SET_ID.test(value)) throw new TypingFeelJobError(`${label} ${describe(value)} must be 1 to 32 lower-case letters, digits or dashes, starting with a letter or digit.`);
  if (RESERVED_IDS.has(value)) throw new TypingFeelJobError(`${label} "${value}" is reserved for the games' silent choice.`);
  return value;
}

function cleanFamily(value) {
  if (value === undefined || value === null || value === "") return null;
  if (typeof value !== "string" || !SET_ID.test(value)) throw new TypingFeelJobError(`Family ${describe(value)} must be a family id.`);
  return value;
}

/** Owner listening score (decision 5): a number from 0 to 10 in half steps. Never defaulted. */
function cleanScore(value) {
  if (typeof value !== "number" || !Number.isFinite(value) || value < 0 || value > 10 || Math.round(value * 2) !== value * 2) {
    throw new TypingFeelJobError("Owner score must be a number from 0 to 10 (half points allowed). Listen to the A/B, then score it.");
  }
  return value;
}

/**
 * Megabytes of a file over the limit, rounded up to two decimals (natural.py
 * fmt_past): 50 MiB + 1 byte reads 50.01, never "50.0 MB; the limit is 50 MB".
 */
export function megabytesPast(bytes) {
  const value = Math.ceil((bytes / 1024 / 1024) * 100 - 1e-6) / 100;
  return value.toFixed(2).replace(/\.?0+$/, "");
}

function stamp(date) {
  const iso = date.toISOString();
  return `${iso.slice(0, 4)}${iso.slice(5, 7)}${iso.slice(8, 10)}-${iso.slice(11, 13)}${iso.slice(14, 16)}${iso.slice(17, 19)}`;
}

async function fileSha256(path) {
  const hash = createHash("sha256");
  for await (const chunk of createReadStream(path)) hash.update(chunk);
  return hash.digest("hex");
}

async function readTail(path, bytes = LOG_TAIL) {
  let handle;
  try {
    handle = await open(path, "r");
    const { size } = await handle.stat();
    const length = Math.min(size, bytes);
    const buffer = Buffer.alloc(length);
    await handle.read(buffer, 0, length, size - length);
    return buffer.toString("utf8");
  } catch (error) {
    if (error?.code === "ENOENT") return "";
    throw error;
  } finally {
    await handle?.close();
  }
}

function mimeFor(name) {
  if (name.endsWith(".ogg")) return "audio/ogg";
  if (name.endsWith(".mp3")) return "audio/mpeg";
  if (name.endsWith(".json")) return "application/json; charset=utf-8";
  return "text/plain; charset=utf-8";
}

/** Component role of a served file name (Accept stores these roles, §3.6). */
export function roleForFile(name) {
  if (name === "keys-manifest.json") return "manifest";
  if (name === "preview.ogg") return "preview";
  if (name === "report.json") return "report";
  if (AB_FILES[name]) return AB_FILES[name];
  const match = AUDIO_FILE.exec(name);
  return match ? `${match[1]}-${match[2]}` : null;
}

