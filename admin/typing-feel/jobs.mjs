/** What job.json keeps of report.json (the whole report is served on its own). */
export function reportSummary(report) {
  if (!report || typeof report !== "object") return null;
  return {
    status: report.status ?? null,
    counts: report.counts ?? null,
    minimum: report.minimum ?? null,
    acceptAllowed: report.acceptAllowed === true,
    gatesPass: report.gates?.pass ?? null,
    gatesFailed: Array.isArray(report.gates?.failed) ? report.gates.failed : [],
    leadIns: Array.isArray(report.leadIns) ? report.leadIns.length : 0,
    warnings: Array.isArray(report.warnings) ? report.warnings.slice(0, 60) : [],
    lengthsMs: report.lengthsMs ?? null,
    loudness: report.loudness ?? null,
    taps: report.taps ? { found: report.taps.found, usable: report.taps.usable, main: report.taps.main } : null,
    seconds: report.seconds ?? null,
    upload: report.upload ? { ok: report.upload.ok, errors: report.upload.errors ?? [], warnings: report.upload.warnings ?? [], source: report.upload.source ?? null } : null,
  };
}

/** One-line serial queue (a promise chain); `run` returns the operation's promise. */
function serialQueue() {
  let tail = Promise.resolve();
  return (operation) => {
    const next = tail.then(operation, operation);
    tail = next.then(() => undefined, () => undefined);
    return next;
  };
}

export class TypingFeelJobs {
  /**
   * @param store      TypingFeelRevisionStore (jobs live in <store.rootDir>/jobs)
   * @param service    TypingFeelService (Accept stores the bundle through its write queue)
   * @param mediaStore MediaAssetStore
   * @param tool       { command, args, cwd, env } (defaultFormatTool)
   * @param machine    async () => { ready, problems } (checkFormatMachine)
   */
  constructor({ store, service, mediaStore, tool, machine = () => checkFormatMachine({ env: tool?.env }), timeoutMs = JOB_TIMEOUT_MS, checkTimeoutMs = CHECK_TIMEOUT_MS, retentionMs = JOB_RETENTION_MS, formattedRetentionMs = FORMATTED_RETENTION_MS, staleMs = JOB_STALE_MS, pidAlive = processAlive, now = () => new Date(), random = () => randomBytes(3).toString("hex"), logger = console }) {
    if (!store || !service || !mediaStore || !tool) throw new TypeError("TypingFeelJobs requires store, service, mediaStore and tool.");
    this.store = store;
    this.service = service;
    this.mediaStore = mediaStore;
    this.tool = tool;
    this.machine = machine;
    this.timeoutMs = timeoutMs;
    this.checkTimeoutMs = checkTimeoutMs;
    this.retentionMs = retentionMs;
    this.formattedRetentionMs = formattedRetentionMs;
    this.staleMs = staleMs;
    this.pidAlive = pidAlive;
    // Which runner owns a queued or running job (job.json runner): this process and this start.
    this.runner = { pid: process.pid, token: randomBytes(6).toString("hex") };
    this.now = now;
    this.random = random;
    this.logger = logger;
    this.jobsDir = join(store.rootDir, "jobs");
    this.runQueue = serialQueue();
    this.stateQueue = serialQueue();
    this.checkQueue = serialQueue();
    this.running = null;
    this.idle = Promise.resolve();
  }

  jobDir(jobId) {
    if (typeof jobId !== "string" || !JOB_ID.test(jobId)) throw new TypingFeelNotFoundError(`Job ${describe(jobId)} does not exist.`);
    return join(this.jobsDir, jobId);
  }

  async #read(jobId) {
    try {
      return JSON.parse(await readFile(join(this.jobDir(jobId), "job.json"), "utf8"));
    } catch (error) {
      if (error?.code === "ENOENT") throw new TypingFeelNotFoundError(`Job ${jobId} does not exist.`);
      throw error;
    }
  }

  async #write(job) {
    job.updatedAt = this.now().toISOString();
    const file = join(this.jobDir(job.jobId), "job.json");
    const temporary = `${file}.${process.pid}.${this.random()}.tmp`;
    await writeFile(temporary, serialize(job), "utf8");
    await rename(temporary, file);
    return job;
  }

  /** Read-modify-write of one job.json, one at a time for the whole runner. */
  #update(jobId, change) {
    return this.stateQueue(async () => {
      const job = await this.#read(jobId);
      const result = await change(job);
      if (result === false) return job;
      return this.#write(job);
    });
  }

  /**
   * Is the runner that wrote this queued or running job gone? Its process is dead,
   * it is an earlier start of this very process id, or the record has not moved
   * for `staleMs` (a reused process id). A job of another Admin service that is
   * still running on the same store is left alone.
   */
  #orphaned(job) {
    const runner = job.runner;
    if (!runner || !Number.isInteger(runner.pid) || runner.pid <= 0) return true;
    if (runner.pid === this.runner.pid) return runner.token !== this.runner.token;
    if (!this.pidAlive(runner.pid)) return true;
    const moved = Date.parse(job.updatedAt ?? job.startedAt ?? job.createdAt ?? "");
    return !Number.isFinite(moved) || this.now().getTime() - moved > this.staleMs;
  }

  /**
   * Start-up: a job still queued or running whose runner is gone belonged to a
   * service that stopped; mark it failed (interrupted). Then sweep old jobs.
   */
  async recover() {
    const recovered = [];
    for (const jobId of await this.#jobIds()) {
      await this.#update(jobId, (job) => {
        if (job.status !== "queued" && job.status !== "running") return false;
        if (!this.#orphaned(job)) return false;
        job.status = "failed";
        job.failure = { kind: "interrupted", message: "The Admin service stopped while this job was waiting or running. Format the take again." };
        job.finishedAt = this.now().toISOString();
        recovered.push(jobId);
        return true;
      }).catch((error) => this.logger.warn(`Typing Feel job ${jobId} could not be recovered: ${error.message}`));
    }
    const removed = await this.sweep();
    return { recovered, removed };
  }

  async #jobIds() {
    let names;
    try {
      names = await readdir(this.jobsDir);
    } catch (error) {
      if (error?.code === "ENOENT") return [];
      throw error;
    }
    return names.filter((name) => JOB_ID.test(name)).sort();
  }

  /**
   * Removes failed and discarded jobs older than the retention (7 days), formatted
   * jobs nobody accepted or discarded after 30 days (each holds a copy of its take,
   * up to 50 MB), and the work folders of accepted jobs.
   */
  async sweep() {
    const removed = [];
    const cutoff = this.now().getTime() - this.retentionMs;
    const formattedCutoff = this.now().getTime() - this.formattedRetentionMs;
    for (const jobId of await this.#jobIds()) {
      let job;
      try {
        job = await this.#read(jobId);
      } catch {
        continue;
      }
      const finished = Date.parse(job.finishedAt ?? job.updatedAt ?? job.createdAt ?? "");
      const old = Number.isFinite(finished) && (job.status === "succeeded" ? finished < formattedCutoff : finished < cutoff);
      if ((job.status === "failed" || job.status === "discarded" || job.status === "succeeded") && old) {
        await rm(this.jobDir(jobId), { recursive: true, force: true });
        removed.push(jobId);
      } else if (job.status === "accepted") {
        await this.#removeWork(jobId);
      }
    }
    return removed;
  }

  async #removeWork(jobId) {
    const dir = this.jobDir(jobId);
    await rm(join(dir, "in"), { recursive: true, force: true });
    await rm(join(dir, "out"), { recursive: true, force: true });
  }

  /** A Media V2 version usable as a Format source; returns { asset, version, component, path }. */
  async source(assetVersionId) {
    if (typeof assetVersionId !== "string" || !/^media-version\.[a-z0-9._:-]{1,150}$/.test(assetVersionId)) {
      throw new TypingFeelJobError("sourceAssetVersionId must be the Media V2 version of an uploaded take.");
    }
    let version;
    let asset;
    try {
      version = await this.mediaStore.getVersion(assetVersionId);
      asset = await this.mediaStore.getAsset(version.assetId);
    } catch {
      throw new TypingFeelNotFoundError(`Media V2 version ${assetVersionId} does not exist. Upload the take again.`);
    }
    const problems = [];
    if (asset.kind !== "audio") problems.push(`Media asset ${asset.assetId} is ${asset.kind}, not audio.`);
    for (const tag of SOURCE_TAGS) if (!asset.tags.includes(tag)) problems.push(`Media asset ${asset.assetId} must carry the tag ${tag} (upload it from Add sound set).`);
    if (asset.lifecycle === "archived") problems.push(`Media asset ${asset.assetId} is archived; restore it first.`);
    const component = version.components.length === 1 ? version.components[0] : null;
    if (!component || component.storageClass !== "admin-blob" || typeof component.storageKey !== "string") problems.push(`Media V2 version ${assetVersionId} is not a single uploaded file.`);
    else if (component.byteSize > UPLOAD_RULES.maxBytes) problems.push(`The file is ${megabytesPast(component.byteSize)} MB; the limit is 50 MB.`);
    if (problems.length) throw new TypingFeelJobError(problems.length === 1 ? problems[0] : `${problems.length} problems: ${problems.join(" ")}`, problems);
    const path = join(this.mediaStore.mediaRoot, component.storageKey);
    const blobs = await realpath(join(this.mediaStore.mediaRoot, "blobs"));
    const real = await realpath(path).catch(() => null);
    if (real === null || !real.startsWith(`${blobs}${sep}`) || !(await lstat(real)).isFile()) {
      throw new TypingFeelJobError(`The bytes of ${assetVersionId} are missing from Media V2.`);
    }
    const fileName = typeof version.source?.sourcePath === "string" ? version.source.sourcePath : asset.title;
    return { asset, version, component, path: real, fileName };
  }

  /** Ids a new set may not take: live, retired (now or in any published revision), or ever published (§3.13). */
  async #idRegister() {
    if (!(await this.store.isInitialized())) return null;
    const keyboard = (await this.store.getActiveRevision()).config.keyboard;
    // Ids in the saved draft (the same rule as the service's state.draft: never published, saved since the live
    // revision went live) are taken too, so a new set never lands on a draft row.
    const state = await this.store.getState();
    let draft = null;
    for (const entry of await this.store.listRevisions()) {
      if (!entry.publishable || entry.createdAt < state.updatedAt || (await this.store.getPublication(entry.revision))) continue;
      draft = entry;
      break;
    }
    return {
      live: new Set(keyboard.sets.map((set) => set.id)),
      draft: new Set(draft?.config?.keyboard?.sets?.map((set) => set.id) ?? []),
      retired: new Set([...keyboard.retiredIds, ...(await this.store.reservedRetiredIds())]),
      published: await this.store.publishedSetVersions(),
    };
  }

  static #idProblem(register, setId) {
    if (!register) return null;
    // Re-format (§3.7) is not built yet: a new take of a live set goes in under a new id.
    if (register.live.has(setId)) return `Set id "${setId}" is already a live set; choose a new id. Replacing a live set's sound (Re-format) is not available yet: add the new take under a new id, then hide or retire the old set.`;
    if (register.retired.has(setId)) return `Set id "${setId}" was retired and is never used again (old saves may still hold it); choose another id.`;
    if (register.published.has(setId)) return `Set id "${setId}" was published before and taken out by a Rollback; player saves may still hold it, so it never names a different sound. Choose another id.`;
    if (register.draft?.has(setId)) return `Set id "${setId}" is already in the saved draft; choose another id.`;
    return null;
  }

  /** A set id the Admin may give a new set: not live, not retired, never published before. */
  async #newSetIdProblem(setId) {
    return TypingFeelJobs.#idProblem(await this.#idRegister(), setId);
  }

  /**
   * The id Format gives a take when none was typed: the file name's slug, or the
   * first free `<slug>-2`, `<slug>-3`… (the slug is only a placeholder; Accept sets
   * the final id), so a take named like a live or retired set still formats.
   */
  async #freeSetId(fileName) {
    const register = await this.#idRegister();
    const base = slugFromName(fileName);
    for (let n = 1; n < 1000; n += 1) {
      const suffix = n === 1 ? "" : `-${n}`;
      const candidate = `${base.slice(0, 32 - suffix.length).replace(/-+$/, "")}${suffix}`;
      if (SET_ID.test(candidate) && !RESERVED_IDS.has(candidate) && TypingFeelJobs.#idProblem(register, candidate) === null) return candidate;
    }
    throw new TypingFeelJobError(`No free set id starts with "${base}"; type an id.`);
  }

  /** Upload rules only (§3.8 step 1): runs `keys natural --check --json` on the Media blob. Writes nothing. */
  check(sourceAssetVersionId) {
    return this.checkQueue(async () => {
      const source = await this.source(sourceAssetVersionId);
      const machine = await this.machine();
      if (!machine.ready) return { ok: false, machine, errors: [], warnings: [], notes: [], rules: [], source: { file: source.fileName }, message: machineMessage(machine.problems) };
      const result = await this.#spawn([...this.tool.args, "--check", "--json", `--src=${source.path}`], { timeoutMs: this.checkTimeoutMs });
      let parsed = null;
      try {
        parsed = JSON.parse(result.stdout);
      } catch {
        parsed = null;
      }
      if ((result.code === 0 || result.code === 1) && parsed && typeof parsed === "object") {
        return { ...parsed, source: { ...(parsed.source ?? {}), file: source.fileName }, machine };
      }
      const why = result.timedOut ? `the check took longer than ${Math.round(this.checkTimeoutMs / 1000)} s` : `the tool stopped with exit ${result.code ?? result.signal}`;
      throw new TypingFeelJobError(`The upload check could not run: ${why}. ${lastLines(result.stderr) || `Run \`${SETUP_COMMAND}\` on this machine.`}`.trim());
    });
  }

  /**
   * Format (§3.8 step 2): validates the source and the set id, writes jobs/<id>/job.json
   * as queued and queues the run. Returns the job at once (the HTTP route answers 202).
   */
  async create({ sourceAssetVersionId, recipe = FORMAT_RECIPE, setId, name, family, actorId = "local-admin" }) {
    if (!FORMAT_RECIPES.includes(recipe)) throw new TypingFeelJobError(`Recipe ${describe(recipe)} cannot Format; the Admin offers ${FORMAT_RECIPES.join(", ")} only.`);
    const source = await this.source(sourceAssetVersionId);
    const typed = !(setId === undefined || setId === null || setId === "");
    const setName = name === undefined || name === null || name === "" ? titleFromName(source.fileName) : cleanText(name, "Set name", SET_NAME_MAX);
    const familyId = cleanFamily(family);
    // Only an id someone typed is refused; the default from the file name steps to the next free one.
    let id;
    if (typed) {
      id = cleanSetId(setId);
      const taken = await this.#newSetIdProblem(id);
      if (taken) throw new TypingFeelJobError(taken);
    } else {
      id = await this.#freeSetId(source.fileName);
    }
    const created = this.now();
    const jobId = `j${stamp(created)}-${this.random()}`;
    const dir = this.jobDir(jobId);
    await mkdir(dir, { recursive: true });
    const job = {
      schema: JOB_SCHEMA,
      jobId,
      recipe,
      status: "queued",
      failure: null,
      source: { assetId: source.asset.assetId, assetVersionId: source.version.assetVersionId, title: source.asset.title, fileName: source.fileName, sha256: source.component.sha256, byteSize: source.component.byteSize },
      set: { id, name: setName, family: familyId },
      runner: { ...this.runner },
      createdAt: created.toISOString(),
      createdBy: actorId,
      startedAt: null,
      finishedAt: null,
      exitCode: null,
      summary: null,
      accepted: null,
      logTail: "",
    };
    await writeFile(join(dir, "job.json"), serialize({ ...job, updatedAt: job.createdAt }), { encoding: "utf8", flag: "wx" });
    this.idle = this.runQueue(() => this.#run(jobId)).catch((error) => this.logger.error(`Typing Feel job ${jobId} failed unexpectedly:`, error?.stack ?? error));
    void this.sweep().catch(() => undefined);
    return { ...job, updatedAt: job.createdAt };
  }

  /**
   * Stops the Format tool this runner is running, with its whole process group
   * (run.sh, Python and ffmpeg), so stopping the Admin service never leaves it
   * writing into a job folder. Returns true when there was one.
   */
  stopRunning(signal = "SIGTERM") {
    const child = this.running?.child;
    if (!child?.pid || child.exitCode !== null || child.signalCode !== null) return false;
    try {
      if (process.platform !== "win32") process.kill(-child.pid, signal);
      else child.kill(signal);
    } catch {
      return false;
    }
    return true;
  }

  /** Resolves once every queued job has finished (tests, shutdown). */
  async whenIdle() {
    let seen;
    do {
      seen = this.idle;
      await seen;
    } while (seen !== this.idle);
  }

  async #fail(jobId, failure, extra = {}) {
    const log = await readTail(join(this.jobDir(jobId), "log.txt"));
    return this.#update(jobId, (job) => {
      job.status = "failed";
      job.failure = failure;
      job.finishedAt = this.now().toISOString();
      job.logTail = log;
      Object.assign(job, extra);
    });
  }

  async #run(jobId) {
    const job = await this.#read(jobId);
    if (job.status !== "queued") return;
    const dir = this.jobDir(jobId);
    const log = join(dir, "log.txt");
    await this.#update(jobId, (current) => {
      if (current.status !== "queued") return false;
      current.status = "running";
      current.runner = { ...this.runner };
      current.startedAt = this.now().toISOString();
    });
    if ((await this.#read(jobId)).status !== "running") return;
    try {
      const machine = await this.machine();
      if (!machine.ready) return await this.#fail(jobId, { kind: "machine", message: machineMessage(machine.problems), setupCommand: SETUP_COMMAND });

      // The source WAV, copied out of Media V2 (Python never reads the registry or the blobs folder).
      let source;
      try {
        source = await this.source(job.source.assetVersionId);
      } catch (error) {
        return await this.#fail(jobId, { kind: "source", message: error.message });
      }
      const inDir = join(dir, "in");
      const outDir = join(dir, "out");
      await mkdir(inDir, { recursive: true });
      const sourceFile = join(inDir, "source.wav");
      await rm(sourceFile, { force: true });
      await copyFile(source.path, sourceFile, constants.COPYFILE_EXCL);
      if ((await fileSha256(sourceFile)) !== job.source.sha256) return await this.#fail(jobId, { kind: "source", message: "The copied take does not match its Media V2 sha256." });
      await rm(outDir, { recursive: true, force: true });

      const args = [...this.tool.args, `--src=${sourceFile}`, `--out=${outDir}`, `--id=${job.set.id}`, `--name=${job.set.name}`, ...(job.set.family ? [`--family=${job.set.family}`] : [])];
      await appendFile(log, `$ keys natural --src=in/source.wav --out=out --id=${job.set.id} --name=${JSON.stringify(job.set.name)}${job.set.family ? ` --family=${job.set.family}` : ""}\n`);
      const result = await this.#spawn(args, { timeoutMs: this.timeoutMs, logFile: log, jobId });
      const exitCode = result.code;
      if (result.timedOut) return await this.#fail(jobId, { kind: "timeout", message: `Format took longer than ${Math.round(this.timeoutMs / 1000)} s and was stopped. Try again; if it happens again, check the take's length and the Admin log.` }, { exitCode });
      if (result.spawnError) return await this.#fail(jobId, { kind: "machine", message: machineMessage([`The tool could not start (${result.spawnError}).`]), setupCommand: SETUP_COMMAND });

      const report = await readFile(join(outDir, "report.json"), "utf8").then((text) => JSON.parse(text)).catch(() => null);
      if (exitCode === 1) {
        const errors = Array.isArray(report?.upload?.errors) && report.upload.errors.length ? report.upload.errors : [lastLines(result.stderr) || "The take breaks an upload rule."];
        return await this.#fail(jobId, { kind: "refused", message: "The take breaks the upload rules; nothing was formatted.", errors }, { exitCode, summary: reportSummary(report) });
      }
      if (exitCode === 2) return await this.#fail(jobId, { kind: "machine", message: `${lastLines(result.stderr) || "The Format tool could not run."} Run \`${SETUP_COMMAND}\` on this machine if a tool is missing.`, setupCommand: SETUP_COMMAND }, { exitCode });
      if (exitCode !== 0) return await this.#fail(jobId, { kind: "crashed", message: `Format failed (exit ${exitCode ?? result.signal}): ${lastLines(result.stderr) || "see the log"}` }, { exitCode });

      const problems = await this.#outputProblems(outDir, report);
      if (problems.length) return await this.#fail(jobId, { kind: "output", message: "The Format tool finished but its output is incomplete.", errors: problems }, { exitCode });
      const tail = await readTail(log);
      await this.#update(jobId, (current) => {
        current.status = "succeeded";
        current.finishedAt = this.now().toISOString();
        current.exitCode = exitCode;
        current.summary = reportSummary(report);
        current.logTail = tail;
      });
    } catch (error) {
      await this.#fail(jobId, { kind: "crashed", message: `Format failed: ${error?.message ?? String(error)}` }).catch(() => undefined);
    }
  }

  /** Runs the tool; never through a shell. Resolves { code, signal, stdout, stderr, timedOut, spawnError }. */
  #spawn(args, { timeoutMs, logFile = null, jobId = null }) {
    return new Promise((done) => {
      let child;
      try {
        child = spawn(this.tool.command, args, { cwd: this.tool.cwd, env: this.tool.env, stdio: ["ignore", "pipe", "pipe"], shell: false, detached: process.platform !== "win32" });
      } catch (error) {
        done({ code: null, signal: null, stdout: "", stderr: "", timedOut: false, spawnError: error.message });
        return;
      }
      if (jobId) this.running = { jobId, child };
      let stdout = "";
      let stderr = "";
      let logged = 0;
      let writes = Promise.resolve();
      const capture = (stream, keep) => stream.on("data", (chunk) => {
        if (keep === "out" && stdout.length < STDOUT_LIMIT) stdout += chunk.toString("utf8");
        if (keep === "err") stderr = (stderr + chunk.toString("utf8")).slice(-LOG_TAIL);
        if (logFile && logged < LOG_LIMIT) {
          const piece = chunk.subarray(0, LOG_LIMIT - logged);
          logged += piece.length;
          writes = writes.then(() => appendFile(logFile, piece)).catch(() => undefined);
        }
      });
      capture(child.stdout, "out");
      capture(child.stderr, "err");
      let timedOut = false;
      let finished = false;
      const stop = (signal) => {
        try {
          if (child.pid && process.platform !== "win32") process.kill(-child.pid, signal);
          else child.kill(signal);
        } catch {
          // already gone
        }
      };
      const timer = setTimeout(() => {
        timedOut = true;
        stop("SIGTERM");
        setTimeout(() => {
          if (!finished) stop("SIGKILL");
        }, KILL_GRACE_MS).unref();
      }, timeoutMs);
      child.on("error", (error) => {
        if (finished) return;
        finished = true;
        clearTimeout(timer);
        if (jobId) this.running = null;
        done({ code: null, signal: null, stdout, stderr, timedOut, spawnError: error.message });
      });
      child.on("close", (code, signal) => {
        if (finished) return;
        finished = true;
        clearTimeout(timer);
        if (jobId) this.running = null;
        writes.then(() => done({ code, signal, stdout, stderr, timedOut, spawnError: null }));
      });
    });
  }

  /** The tool's output folder holds exactly a set, its A/B takes and report.json, as regular files. */
  async #outputProblems(outDir, report) {
    const problems = [];
    if (!report || report.status !== "formatted") return ["report.json is missing or does not say formatted."];
    let manifest = null;
    try {
      manifest = JSON.parse(await readFile(join(outDir, "keys-manifest.json"), "utf8"));
    } catch {
      return ["keys-manifest.json is missing or unreadable."];
    }
    const listed = new Set((Array.isArray(manifest.files) ? manifest.files : []).map((entry) => entry?.file));
    const seen = new Set();
    for (const entry of await readdir(outDir, { withFileTypes: true })) {
      if (entry.name === "ab" && entry.isDirectory()) {
        for (const take of await readdir(join(outDir, "ab"), { withFileTypes: true })) {
          if (!AB_FILES[take.name] || !take.isFile()) problems.push(`Unexpected ab/${take.name}.`);
          else seen.add(take.name);
        }
        continue;
      }
      if (!entry.isFile()) problems.push(`${entry.name} is not a regular file.`);
      else if (!roleForFile(entry.name)) problems.push(`Unexpected file ${entry.name}.`);
      else seen.add(entry.name);
    }
    for (const name of ["keys-manifest.json", "preview.ogg", "report.json", ...Object.keys(AB_FILES)]) if (!seen.has(name)) problems.push(`${name} is missing.`);
    for (const name of listed) if (!seen.has(name)) problems.push(`${name} is in keys-manifest.json but was not written.`);
    for (const name of seen) if (AUDIO_FILE.test(name) && !listed.has(name)) problems.push(`${name} is not in keys-manifest.json.`);
    return problems;
  }

  async get(jobId) {
    const job = await this.#read(jobId);
    const dir = this.jobDir(jobId);
    const live = job.status === "running" || job.status === "queued";
    const logTail = live ? await readTail(join(dir, "log.txt")) : job.logTail ?? "";
    let report = null;
    if (job.status === "succeeded" || job.status === "failed") report = await readFile(join(dir, "out", "report.json"), "utf8").then((text) => JSON.parse(text)).catch(() => null);
    else if (job.status === "accepted" && job.accepted?.assetVersionId) report = await this.#acceptedFile(job, "report.json").then((file) => (file ? JSON.parse(file.body.toString("utf8")) : null)).catch(() => null);
    const elapsedFrom = job.startedAt ? Date.parse(job.startedAt) : null;
    return {
      job: { ...job, logTail: undefined },
      log: logTail,
      report,
      elapsedSeconds: elapsedFrom ? Math.round(((job.finishedAt ? Date.parse(job.finishedAt) : this.now().getTime()) - elapsedFrom) / 100) / 10 : null,
      timeoutSeconds: Math.round(this.timeoutMs / 1000),
      filesBase: `/api/admin/shared/typing-feel/jobs/${jobId}/files/`,
    };
  }

  async list({ limit = 20 } = {}) {
    const ids = (await this.#jobIds()).reverse().slice(0, Math.max(1, Math.min(100, limit)));
    const jobs = [];
    for (const jobId of ids) {
      try {
        const job = await this.#read(jobId);
        jobs.push({ jobId, status: job.status, recipe: job.recipe, source: job.source, set: job.set, createdAt: job.createdAt, finishedAt: job.finishedAt, failure: job.failure ? { kind: job.failure.kind, message: job.failure.message } : null, accepted: job.accepted ? { setId: job.accepted.setId, assetVersionId: job.accepted.assetVersionId, status: job.accepted.status } : null, counts: job.summary?.counts ?? null, acceptAllowed: job.summary?.acceptAllowed ?? null });
      } catch {
        // a job folder being written or removed
      }
    }
    return { jobs, running: this.running?.jobId ?? null };
  }

  async #acceptedFile(job, name) {
    const role = roleForFile(name);
    if (!role) return null;
    try {
      const component = await this.mediaStore.resolveComponent(job.accepted.assetVersionId, role);
      if (!component.absolutePath) return null;
      return { body: await readFile(component.absolutePath), contentType: mimeFor(name) };
    } catch {
      return null;
    }
  }

  /** One file of a job for the Listen step; `name` is one segment checked against JOB_FILE. */
  async file(jobId, name) {
    if (typeof name !== "string" || !JOB_FILE.test(name)) return null;
    const job = await this.#read(jobId);
    const dir = this.jobDir(jobId);
    if (name === "log.txt") {
      const body = await readFile(join(dir, "log.txt")).catch(() => null);
      return body ? { body, contentType: mimeFor(name) } : null;
    }
    if (job.status === "accepted") return this.#acceptedFile(job, name);
    const out = join(dir, "out");
    const target = AB_FILES[name] ? join(out, "ab", name) : join(out, name);
    let base;
    let real;
    try {
      base = await realpath(out);
      real = await realpath(target);
    } catch {
      return null;
    }
    if (!real.startsWith(`${base}${sep}`) || !(await lstat(real)).isFile()) return null;
    return { body: await readFile(real), contentType: mimeFor(name) };
  }

  /** Discard (§3.8): the job and its files go; a running job is left to finish. */
  async discard(jobId, { actorId = "local-admin" } = {}) {
    const job = await this.#update(jobId, (current) => {
      if (current.status === "running") throw new AdminConflictError("This job is running; wait for it to finish, then discard it.");
      if (current.status === "accepted") throw new AdminConflictError("This job was accepted; its set is in Media V2. Remove the set from the draft instead.");
      if (current.status === "discarded") return false;
      current.status = "discarded";
      current.discardedAt = this.now().toISOString();
      current.discardedBy = actorId;
      current.finishedAt ??= current.discardedAt;
    });
    await this.#removeWork(jobId);
    return job;
  }

  /**
   * Accept (§3.8 step 4, decision 5): stores the formatted set as one immutable
   * Media V2 bundle version and returns the set row the draft gets. The page adds
   * the row to the working copy; Save draft → Review → Publish does the rest.
   * Input: { setId, name, family, licence?, ownerScore, reason?, note? }.
   */
  accept(jobId, input = {}, { actorId = "local-admin" } = {}) {
    return this.stateQueue(async () => {
      const job = await this.#read(jobId);
      if (job.status === "accepted") throw new AdminConflictError(`Job ${jobId} was already accepted as ${job.accepted?.assetVersionId}.`);
      if (job.status !== "succeeded") throw new AdminConflictError(`Job ${jobId} is ${job.status}; only a formatted job can be accepted.`);
      const setId = cleanSetId(input.setId);
      const name = cleanText(input.name, "Set name", SET_NAME_MAX);
      const family = cleanFamily(input.family);
      if (!family) throw new TypingFeelJobError("Choose the family the set joins.");
      const licence = cleanText(input.licence ?? DEFAULT_LICENCE, "Licence", LICENCE_MAX);
      const ownerScore = cleanScore(input.ownerScore);
      const status = ownerScore >= PUBLISHED_OWNER_SCORE ? "published" : "provisional";
      const reason = cleanText(input.reason, "Reason", NOTE_MAX, { required: false });
      const note = cleanText(input.note, "Note", NOTE_MAX, { required: false });
      if (status === "provisional" && !reason) throw new TypingFeelJobError(`Owner score ${ownerScore} is under ${PUBLISHED_OWNER_SCORE}: the set can only be Provisional, and a Provisional set needs a reason.`);
      if (!(await this.store.isInitialized())) throw new TypingFeelJobError("Typing Feel is not imported yet; run the one-off import first.");
      // The family may be new in the page's working copy, so only its id is checked here; Save draft checks the rest.
      const taken = await this.#newSetIdProblem(setId);
      if (taken) throw new TypingFeelJobError(taken);

      const outDir = join(this.jobDir(jobId), "out");
      let report;
      let manifest;
      try {
        report = JSON.parse(await readFile(join(outDir, "report.json"), "utf8"));
        manifest = JSON.parse(await readFile(join(outDir, "keys-manifest.json"), "utf8"));
      } catch {
        throw new AdminConflictError(`The files of job ${jobId} are gone; Format the take again.`);
      }
      if (report.status !== "formatted" || report.acceptAllowed !== true) {
        throw new TypingFeelJobError(`Job ${jobId} cannot be accepted: ${report.gates?.pass === false ? `hard gates failed (${(report.gates.failed ?? []).join(", ")})` : `${report.counts?.key ?? 0} keys and ${report.counts?.space ?? 0} spaces; a set needs at least ${report.minimum?.key ?? 10} and ${report.minimum?.space ?? 3}`}.`);
      }
      const problems = await this.#outputProblems(outDir, report);
      if (problems.length) throw new TypingFeelJobError(`The files of job ${jobId} are incomplete: ${problems.join(" ")}`, problems);

      // The set manifest takes its final id, name and licence (JSON only; the audio is never re-encoded).
      const finalManifest = { ...manifest, id: setId, name, licence };
      const manifestText = setManifestText(finalManifest);
      const acceptedAt = this.now().toISOString();
      const finalReport = {
        ...report,
        set: { ...(report.set ?? {}), id: setId, name, family, licence },
        manifest: { ...(report.manifest ?? {}), sha256: sha256(Buffer.from(manifestText)) },
        accept: { jobId, ownerScore, status, reason: reason ?? null, acceptedAt, acceptedBy: actorId, source: job.source.assetVersionId },
      };
      const durations = new Map((Array.isArray(manifest.files) ? manifest.files : []).map((entry) => [entry.file, entry.durationMs]));
      const components = [
        { role: "manifest", filename: "keys-manifest.json", mimeType: "application/json", buffer: Buffer.from(manifestText) },
        { role: "report", filename: "report.json", mimeType: "application/json", buffer: Buffer.from(`${JSON.stringify(finalReport, null, 1)}\n`) },
      ];
      const audio = (await readdir(outDir)).filter((name) => AUDIO_FILE.test(name) || name === "preview.ogg").sort();
      for (const file of audio) {
        const durationMs = file === "preview.ogg" ? report.preview?.durationMs : durations.get(file);
        components.push({ role: roleForFile(file), filename: file, mimeType: "audio/ogg", buffer: await readFile(join(outDir, file)), ...(Number.isFinite(durationMs) && durationMs > 0 ? { durationSeconds: durationMs / 1000 } : {}) });
      }
      for (const [file, role] of Object.entries(AB_FILES)) {
        const seconds = report.ab?.[role === "ab-raw" ? "rawCut" : "natural"]?.seconds;
        components.push({ role, filename: file, mimeType: "audio/mpeg", buffer: await readFile(join(outDir, "ab", file)), ...(Number.isFinite(seconds) && seconds > 0 ? { durationSeconds: seconds } : {}) });
      }
      const generator = typeof report.tool?.generator === "string" && report.tool.generator.trim() ? report.tool.generator.trim().slice(0, 500) : `typing-feel ${job.recipe} (tools/audio-lab keys natural)`;
      const source = { generator, sourcePath: job.source.assetVersionId, license: licence, note: provenanceNote({ recipe: job.recipe, jobId, ownerScore, status, take: job.source.fileName, sourceSha256: job.source.sha256, tool: report.tool }) };
      const { asset, version } = await this.service.acceptSetBundle({ title: name, components, source, actorId });

      const row = {
        id: setId,
        name,
        family,
        order: 0,
        enabled: true,
        status,
        assetVersionId: version.assetVersionId,
        ownerPick: false,
        ownerScore,
        recipe: job.recipe,
        score: null,
        ...(status === "provisional" ? { note: reason } : note ? { note } : {}),
      };
      job.status = "accepted";
      job.finishedAt ??= acceptedAt;
      job.accepted = { setId, name, family, status, ownerScore, reason: reason ?? null, assetId: asset.assetId, assetVersionId: version.assetVersionId, folder: `sets/${setId}/${version.contentFingerprint.slice(0, 12)}`, acceptedAt, acceptedBy: actorId, row };
      await this.#write(job);
      await this.#removeWork(jobId);
      return { job, asset, version, row };
    });
  }

  /** What the Add sound set page needs before it starts (§3.12 GET capabilities). */
  async capabilities() {
    const machine = await this.machine();
    return {
      recipes: [...FORMAT_RECIPES],
      machine,
      upload: { ...UPLOAD_RULES, sourceTags: [...SOURCE_TAGS] },
      timeoutSeconds: Math.round(this.timeoutMs / 1000),
      publishedOwnerScore: PUBLISHED_OWNER_SCORE,
      defaultLicence: DEFAULT_LICENCE,
      running: this.running?.jobId ?? null,
      online: { configured: false },
    };
  }
}

/**
 * Media V2 source.note of an accepted set (§3.6: the parameters as JSON, at most
 * 500 characters). The recipe modules' sha256 (first 16 hex, the whole values
 * are in the bundle's report.json) pin the code that made the set even when the
 * git sha of the generator line is "+dirty". Never cut mid-JSON: the take's
 * name, the only open-ended field, is shortened first.
 */
export function provenanceNote({ recipe, jobId, ownerScore, status, take, sourceSha256, tool }) {
  const files = tool && typeof tool.files === "object" && tool.files !== null ? tool.files : {};
  const toolSha256 = Object.fromEntries(Object.entries(files).filter(([name, hash]) => typeof name === "string" && typeof hash === "string" && /^[0-9a-f]{64}$/.test(hash)).map(([name, hash]) => [name, hash.slice(0, 16)]));
  const params = { recipe, job: jobId, ownerScore, status, take: String(take ?? ""), sourceSha256, ...(Object.keys(toolSha256).length ? { toolSha256 } : {}), ...(typeof tool?.dirty === "boolean" ? { toolDirty: tool.dirty } : {}) };
  let text = JSON.stringify(params);
  if (text.length > 500) {
    params.take = params.take.slice(0, Math.max(0, params.take.length - (text.length - 500) - 1));
    text = JSON.stringify(params);
  }
  return text.length > 500 ? JSON.stringify({ recipe, job: jobId, ownerScore, status, sourceSha256 }) : text;
}

function lastLines(text, count = 3) {
  return String(text ?? "").trim().split("\n").filter(Boolean).slice(-count).join(" ").slice(0, 600);
}

function processAlive(pid) {
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return error?.code === "EPERM";
  }
}

const STOP_SIGNALS = Object.freeze(["SIGTERM", "SIGINT", "SIGHUP"]);

/**
 * When the Admin service stops (a signal, or a normal exit), the running Format
 * tool stops with it instead of writing on into its job folder; the next start
 * marks the job interrupted. A signal is passed on afterwards, so the service
 * still ends the way it would without this hook (unless something else listens).
 */
export function stopFormatToolOnExit(jobs, proc = process) {
  const onSignal = (signal) => {
    jobs.stopRunning("SIGTERM");
    for (const name of STOP_SIGNALS) proc.removeListener(name, onSignal);
    if (proc.listenerCount(signal) === 0) proc.kill(proc.pid, signal);
  };
  for (const name of STOP_SIGNALS) proc.on(name, onSignal);
  proc.on("exit", () => jobs.stopRunning("SIGTERM"));
  return onSignal;
}

/** For setup.mjs: the runner, recovered and swept. Never throws (a failure leaves Format off with the reason). */
export async function startTypingFeelJobs({ store, service, mediaStore, repoRoot, env = process.env, logger = console, proc = process }) {
  const jobs = new TypingFeelJobs({ store, service, mediaStore, tool: defaultFormatTool({ repoRoot: resolve(repoRoot), env }), logger });
  stopFormatToolOnExit(jobs, proc);
  try {
    const { recovered, removed } = await jobs.recover();
    if (recovered.length) logger.warn(`Typing Feel: marked ${recovered.length} Format job(s) interrupted: ${recovered.join(", ")}.`);
    if (removed.length) logger.log(`Typing Feel: removed ${removed.length} old failed or discarded Format job(s).`);
  } catch (error) {
    logger.error(`Typing Feel: the Format jobs folder could not be checked: ${error?.message ?? error}`);
  }
  return jobs;
}
