// Typing Feel Format jobs (docs/games/TYPING_FEEL_SERVICE.md §3.8, §3.9 "Chạy job").
//
// One owner take (a WAV uploaded to Media V2 with the tags typing-feel and
// keyboard-source) → the Audio Lab tool `keys natural` → a formatted set in
// <shared store>/jobs/<jobId>/out/, then Listen, Score and Accept, which stores
// the files as one immutable Media V2 bundle version. Nothing here changes a
// revision or anything the games read: the page adds the set to the draft, and
// the existing Save draft → Review → Publish takes it to the games.
//
// - One job at a time on this machine (its own queue, apart from the Typing Feel
//   write queue, so a 3-minute Format never blocks Save draft or Publish).
// - The tool runs as spawn(command, [args…]) with shell: false; every argument is
//   one array item in --flag=value form; every path comes from the store
//   (the Media V2 blob, copied to jobs/<id>/in/source.wav, and jobs/<id>/out).
//   Python never touches the Media V2 registry.
// - 180 s timeout, then the tool's process group is stopped; stopping the Admin
//   service stops it too (stopFormatToolOnExit). job.json names the runner
//   (process id and start token); a queued or running job whose runner is gone
//   is marked failed (interrupted) at the next start, while a job another live
//   Admin service is running on the same store is left alone.
// - job.json: queued | running | succeeded | failed | accepted | discarded.
// - Accepted jobs lose their work folders once the bytes are Media V2 blobs;
//   failed and discarded jobs are removed after 7 days, formatted jobs nobody
//   accepted or discarded after 30 days.
