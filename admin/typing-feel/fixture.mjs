/** Every file under `dir` as relative path → bytes (missing dir → empty map). */
export async function snapshot(dir) {
  const files = new Map();
  const walk = async (relative) => {
    let entries;
    try {
      entries = await readdir(join(dir, relative), { withFileTypes: true });
    } catch (error) {
      if (error.code === "ENOENT") return;
      throw error;
    }
    for (const entry of entries) {
      const child = relative ? `${relative}/${entry.name}` : entry.name;
      if (entry.isDirectory()) await walk(child);
      else files.set(child, await readFile(join(dir, child)));
    }
  };
  await walk("");
  return files;
}

export function sameSnapshot(left, right) {
  if (left.size !== right.size) return false;
  for (const [path, bytes] of left) if (!right.get(path)?.equals(bytes)) return false;
  return true;
}

