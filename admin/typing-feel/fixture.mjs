/**
 * Registers a new Admin-upload keyboard set bundle (fake OGG bytes, a real
 * set-1 manifest) in Media V2, as the G7 Accept step will. Returns the version.
 */
export async function addBundleSet(mediaStore, { id, name = id, keys = 10, spaces = 3, recipe = "natural-v1", salt = "", tags = SET_TAGS } = {}) {
  const files = [];
  for (let n = 1; n <= keys; n += 1) files.push({ file: `key-${String(n).padStart(2, "0")}.ogg`, set: "key", durationMs: 300 + n });
  for (let n = 1; n <= spaces; n += 1) files.push({ file: `space-${String(n).padStart(2, "0")}.ogg`, set: "space", durationMs: 500 + n });
  const manifest = { schema: "typing-feel/set-1", id, name, licence: LICENCE, recipe, files, preview: "preview.ogg" };
  const components = [
    { role: "manifest", filename: "keys-manifest.json", mimeType: "application/json", buffer: Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`) },
    { role: "preview", filename: "preview.ogg", mimeType: "audio/ogg", buffer: Buffer.from(`OggS preview ${id}${salt}\n`) },
    { role: "report", filename: "report.json", mimeType: "application/json", buffer: Buffer.from(`{"id":"${id}"}\n`) },
    ...files.map((entry) => ({ role: entry.file.replace(/\.ogg$/, ""), filename: entry.file, mimeType: "audio/ogg", buffer: Buffer.from(`OggS ${id}/${entry.file}${salt}\n`), durationSeconds: entry.durationMs / 1000 })),
  ];
  const { version } = await mediaStore.createUploadBundleAsset({
    kind: "audio", title: name, tags, components, actorId: "test",
    source: { generator: "typing-feel natural-v1 (test)", license: LICENCE },
  });
  return version;
}

