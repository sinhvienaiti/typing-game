#!/usr/bin/env node
// Test stand-in for `bash tools/audio-lab/run.sh keys natural` (jobs.test.mjs).
// Same command line (--check --json --src=…, or --src= --out= --id= --name= --family=)
// and the same exit codes as tools/audio-lab/keys/natural.py: 0 formatted or check
// passed, 1 refused, 2 usage or machine problem, 3 Format failed. Writes fake OGG
// and MP3 bytes plus a natural-v1-shaped report.json; never decodes audio.
//   FAKE_NATURAL_MODE   ok (default) | refuse | machine | crash | sleep | few | bad-output | gate-fail
//   FAKE_NATURAL_LOG    a file that gets one JSON line per run: { argv, pid, start, end }
//   FAKE_NATURAL_DELAY_MS  wait this long before writing (the one-at-a-time test)
import { appendFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { basename, join } from "node:path";

const argv = process.argv.slice(2);
const mode = process.env.FAKE_NATURAL_MODE || "ok";
const start = Date.now();
const option = (name) => {
  const hit = argv.find((arg) => arg.startsWith(`--${name}=`));
  return hit === undefined ? null : hit.slice(name.length + 3);
};
const record = () => {
  if (process.env.FAKE_NATURAL_LOG) appendFileSync(process.env.FAKE_NATURAL_LOG, `${JSON.stringify({ argv, pid: process.pid, start, end: Date.now(), mode })}\n`);
};
const sleep = (ms) => new Promise((done) => setTimeout(done, ms));
const LICENCE = "Adobe Firefly Generate Sound Effects, generated by the project owner (Adobe model)";

const src = option("src");
const check = argv.includes("--check");
if (!src) {
  console.error("keys natural: give the take once, as <wav> or --src <wav>.");
  record();
  process.exit(2);
}
const delay = Number(process.env.FAKE_NATURAL_DELAY_MS || 0);
if (delay) await sleep(delay);
if (mode === "sleep") {
  console.log("fake: sleeping");
  await sleep(60_000);
}
if (mode === "machine") {
  console.error("keys natural: ffmpeg is not on this machine's PATH; install it (brew install ffmpeg), then run `bash tools/audio-lab/common/setup.sh` on this machine.");
  record();
  process.exit(2);
}
if (mode === "crash") {
  console.error("keys natural: Format failed: RuntimeError: fake crash");
  record();
  process.exit(3);
}

const bytes = existsSync(src) ? readFileSync(src) : Buffer.alloc(0);
const refused = mode === "refuse" || !bytes.subarray(0, 4).equals(Buffer.from("RIFF"));
const errors = refused ? ["Found 7 usable taps; need at least 12, each at least 150 ms before the next."] : [];
const upload = {
  ok: !refused,
  errors,
  warnings: ["Tap at 2.4 s reaches full scale; check it in the A/B."],
  notes: ["About 2.0 taps a second (about 2 a second works best); record dry, close to the microphone, with no music."],
  rules: [
    { id: "format", label: "File type", ok: true, level: "error", value: "WAV", limit: "WAV", message: "" },
    { id: "usableTaps", label: "Usable taps", ok: !refused, level: "error", value: refused ? 7 : 17, limit: 12, message: errors[0] ?? "" },
    { id: "fullScale.3", label: "Peak near 0 dBFS", ok: false, level: "warning", value: 2.4, limit: 0.99, message: "Tap at 2.4 s reaches full scale; check it in the A/B." },
  ],
  source: { file: basename(src), bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex"), sampleRate: 48000, channels: 2, durationS: 8, peakDbfs: -1.76, noiseFloorDbfs: -90.3, tapsFound: 22, tapsUsable: refused ? 7 : 17, tapsMain: 17, tapsPerSecond: 2 },
};
if (check) {
  if (argv.includes("--json")) console.log(JSON.stringify(upload, null, 1));
  record();
  process.exit(refused ? 1 : 0);
}

const out = option("out");
if (!out) {
  console.error("keys natural: give --out <folder> (or --check).");
  record();
  process.exit(2);
}
if (existsSync(out) && readdirSync(out).length) {
  console.error(`keys natural: Output folder ${out} is not empty; give a new folder.`);
  record();
  process.exit(2);
}
mkdirSync(out, { recursive: true });
const id = option("id") || "new-set";
const name = option("name") || "New Set";
const family = option("family");
const report = {
  schema: "typing-feel/natural-report-1",
  recipe: "natural-v1",
  status: "refused",
  tool: { name: "tools/audio-lab keys natural", gitSha: "fake", generator: "typing-feel natural-v1 (tools/audio-lab keys natural @fake)" },
  createdAt: new Date(start).toISOString().replace(/\.\d{3}Z$/, "Z"),
  set: { id, name, family, licence: LICENCE },
  upload,
  warnings: [...upload.warnings],
};
if (refused) {
  writeFileSync(join(out, "report.json"), `${JSON.stringify(report, null, 1)}\n`);
  for (const message of errors) console.error(`refused: ${message}`);
  record();
  process.exit(1);
}

const keys = mode === "few" ? 8 : 12;
const spaces = 8;
const files = [];
const rows = [];
const write = (file, text) => writeFileSync(join(out, file), Buffer.from(`OggS fake ${id} ${file} ${start}\n${text ?? ""}`));
for (const [prefix, count] of [["key", keys], ["space", spaces]]) {
  for (let n = 1; n <= count; n += 1) {
    const file = `${prefix}-${String(n).padStart(2, "0")}.ogg`;
    const durationMs = prefix === "space" ? 535 : 150 + n * 20;
    write(file);
    files.push({ file, set: prefix, durationMs });
    const leadIn = prefix === "key" && n === 4;
    rows.push({ file, set: prefix, tap: n, durationMs, peakDbfs: -3, truePeakDbtp: -2.9, lufsMMax: -30 - n / 4, riseMs: leadIn ? 66 : 1.5, mainStrikeMs: leadIn ? 66 : 2, leadIn, tickDb: leadIn ? -13.5 : null, energyAfter120msPct: 20, stereoCorrelation: 0.8, phaseWarning: false, gates: { clip: true, silent: true, tail: true, dcOffset: true, truePeak: true, sampleRate: true, channels: true } });
  }
}
write("preview.ogg");
if (mode === "bad-output") writeFileSync(join(out, "evil.sh"), "#!/bin/sh\n");
const head = ["schema", "id", "name", "licence", "recipe"].map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify({ schema: "typing-feel/set-1", id, name, licence: LICENCE, recipe: "natural-v1" }[key])},`);
const manifestText = `{\n${head.join("\n")}\n  "files": [\n${files.map((entry) => `    ${JSON.stringify(entry)}`).join(",\n")}\n  ],\n  "preview": "preview.ogg"\n}\n`;
writeFileSync(join(out, "keys-manifest.json"), manifestText);
mkdirSync(join(out, "ab"));
writeFileSync(join(out, "ab", "raw-cut.mp3"), Buffer.from(`ID3 fake raw cut ${id} ${start}\n`));
writeFileSync(join(out, "ab", "natural.mp3"), Buffer.from(`ID3 fake natural ${id} ${start}\n`));
const gatesPass = mode !== "gate-fail";
Object.assign(report, {
  status: "formatted",
  taps: { found: 22, usable: 17, main: keys + spaces, rows: [] },
  counts: { key: keys, space: spaces },
  minimum: { key: 10, space: 3 },
  acceptAllowed: keys >= 10 && gatesPass,
  lengthsMs: { key: [170, 150 + keys * 20], space: [535, 535] },
  loudness: { metric: "LUFS-M max (0.4 s window, padded)", min: -33, max: -30.25, spreadDb: 2.75, truePeakMaxDbtp: -2.9, peakMaxDbfs: -3 },
  leadIns: [{ file: "key-04.ogg", set: "key", mainStrikeMs: 66, tickDb: -13.5 }],
  gates: { pass: gatesPass, failed: gatesPass ? [] : ["key-02.ogg:tail"], checks: ["clip", "silent", "tail", "dcOffset", "truePeak", "sampleRate", "channels"] },
  files: rows,
  preview: { file: "preview.ogg", durationMs: 1000, peakDbfs: -2.5, truePeakDbtp: -2.5, lufsMMax: -26.3, endLevelDb: -88, fadeOutMs: 10, gates: rows[0].gates },
  ab: { rawCut: { file: "ab/raw-cut.mp3", seconds: 16, wpm: 70, lufsI: -31.7 }, natural: { file: "ab/natural.mp3", seconds: 16, wpm: 70, lufsI: -34.1 } },
  manifest: { file: "keys-manifest.json", sha256: createHash("sha256").update(manifestText).digest("hex") },
  seconds: 0.1,
});
report.warnings.push("key-04.ogg: soft tick, then the main strike 66 ms later (kept as recorded; listen in the A/B).");
if (keys < 10) report.warnings.push(`Only ${keys} keys; a set needs at least 10, so Accept stays locked.`);
writeFileSync(join(out, "report.json"), `${JSON.stringify(report, null, 1)}\n`);
console.log(`${id}: ${keys} keys, ${spaces} spaces, 1 lead-ins, gates ${gatesPass ? "pass" : "FAIL"}, accept ${report.acceptAllowed ? "allowed" : "locked"} -> ${out}`);
record();
process.exit(0);
